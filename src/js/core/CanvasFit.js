// Вписывание холста в экран по ВЫСОТЕ, а не только по ширине.
//
// Почему это отдельная функция, а не пара строк в `_displayWidth`: до 31.08 холст подгонялся
// исключительно по ширине (`scale = canvas.getWidth() / img.width` в `canvas.browser.js`),
// а высота молча ехала следом за пропорцией мокапа. На 1366×768 это давало холст 600×661,
// и вместе с рядом эскизов (144 px) страница переливалась на 250 px — замер 31.08. Клиент
// назвал критерий приёмки прямо: «на ноутбуке конструктор помещается без вертикальной
// прокрутки», поэтому ограничение по высоте это требование, а не украшение.
//
// ⚠️ Пропорция у линеек РАЗНАЯ: кадр считается по самой высокой форме линейки, на диске тогда
// 992 (Champion) .. 1110 (Star), сейчас 836 .. 937, при общей ширине 900. Бюджет высоты нельзя перевести
// в ширину одним общим числом — пропорция приходит параметром от конкретного мокапа.

// Тот же нижний потолок, что и у `_displayWidth` на телефоне: уже 150 px форма перестаёт
// быть различимой, и лучше отдать прокрутку, чем нечитаемый холст.
export const MIN_DISPLAY_WIDTH = 150;

/**
 * Ширина холста с учётом бюджета высоты.
 *
 * @param {number} displayWidth ширина, выбранная по горизонтали (`_displayWidth`)
 * @param {number} aspect пропорция мокапа: высота / ширина (992/900 у Champion)
 * @param {number} availHeight сколько пикселей высоты отдано под холст
 * @returns {number} ширина, при которой `ширина * aspect` уже влезает в `availHeight`
 */
export function capWidthByHeight(displayWidth, aspect, availHeight) {
  if (!(aspect > 0)) return displayWidth; // пропорция ещё не известна — не портим ширину
  const byHeight = Math.floor(availHeight / aspect);
  return Math.max(MIN_DISPLAY_WIDTH, Math.min(displayWidth, byHeight));
}

// ─── ОДНА БЕЛАЯ РАМКА НА ВСЕ ЛИНЕЙКИ (клиент 02.09, волна 5) ────────────────────────────────
//
// Клиент дословно: «наша сейчас задача — сделать так, чтобы на всех картинках вот эта белая
// рамка была без движения, чтобы она была намертво зафиксирована, и чтобы она была одна, чтобы
// она не гуляла вверх-вниз… а внутри они пускай плавают как хотят». И отдельно: «Чемпион — да,
// всё отлично, просто вот идеальные размеры». Расшифровка — docs/voice-client-2026-09-02.txt.
//
// Что было: кадры мокапов на диске имеют ОДНУ ширину 900, но РАЗНУЮ высоту — она считается по
// самой высокой форме линейки: Champion 836, Legend 850, Фаворит 869, Winner 871, Волна 875,
// Star 878, Space 879, New 937 (⚠️ Star был 954, пока кадр держало сырое фото `Star чёрный`
// с гетрами; 03.09 клиент прислал композит, самой высокой стала New). Холст вписывался
// по пропорции конкретного мокапа, поэтому белая
// карточка меняла размер при каждом переключении линейки. Симптом ЗЕРКАЛЬНЫЙ: на ПК упирается
// высота (465) и гуляет ширина 439…501, на телефоне упирается ширина (388) и гуляет высота
// 360…411. Клиент смотрит с телефона и видит «фон стал уже, снизу отступ вырос».
//
// ⚠️ Почему НЕ буквальные 900×1200, которые он предложил. Экран всё равно вписывает кадр по
// своей стороне, поэтому решает только ПРОПОРЦИЯ, а абсолютные 900 и 1200 не значат ничего:
// 900×1200 дало бы 349 px на ПК (−30 % к «идеальному Чемпиону») и 517 на телефоне (+44 %,
// с риском вертикального перелива, который волна 4 только что вылечила). 836/900 даёт 500 и 360
// у ВСЕХ восьми — ровно нынешнего Чемпиона. Требование «рамка одна и не гуляет» выполняется
// в обоих вариантах; берём тот, что не ломает уже принятое.
//
// ⚠️ Правим карточку, а НЕ 45 картинок. Доли зон считаются от холста (zoneToRect умножает на
// canvas.width/height), холст сохраняет собственную пропорцию мокапа — значит зоны не съезжают
// ни на пиксель, и перерисовывать WebP с белыми полями не нужно. Белые поля даёт сама карточка:
// фон мокапа (255,255,255) и --stage-card (#ffffff) — один цвет, шва не видно.
export const FRAME_ASPECT = 836 / 900;

/**
 * Размеры белой карточки с постоянной пропорцией и вписанного в неё холста.
 * Картинка выше рамки — прижимается по высоте, по бокам остаётся белое поле (клиент: «пускай
 * плавают внутри»). Картинка ровно по рамке (Champion) — заполняет её целиком, как сейчас.
 *
 * @param {number} cardWidth ширина белой карточки (уже с учётом бюджета высоты)
 * @param {number} imgAspect пропорция мокапа: высота / ширина
 * @returns {{cardWidth:number, cardHeight:number, canvasWidth:number, canvasHeight:number}}
 */
export function fitCanvasInCard(cardWidth, imgAspect) {
  const cardHeight = cardWidth * FRAME_ASPECT;
  if (!(imgAspect > 0)) {
    return { cardWidth, cardHeight, canvasWidth: cardWidth, canvasHeight: cardHeight };
  }
  const canvasWidth = imgAspect > FRAME_ASPECT ? cardHeight / imgAspect : cardWidth;
  return { cardWidth, cardHeight, canvasWidth, canvasHeight: canvasWidth * imgAspect };
}
