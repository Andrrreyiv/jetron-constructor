// Вписывание холста в экран по ВЫСОТЕ, а не только по ширине.
//
// Почему это отдельная функция, а не пара строк в `_displayWidth`: до 31.08 холст подгонялся
// исключительно по ширине (`scale = canvas.getWidth() / img.width` в `canvas.browser.js`),
// а высота молча ехала следом за пропорцией мокапа. На 1366×768 это давало холст 600×661,
// и вместе с рядом эскизов (144 px) страница переливалась на 250 px — замер 31.08. Клиент
// назвал критерий приёмки прямо: «на ноутбуке конструктор помещается без вертикальной
// прокрутки», поэтому ограничение по высоте это требование, а не украшение.
//
// ⚠️ Пропорция у линеек РАЗНАЯ: кадр считается по самой высокой форме линейки, на диске
// 992 (Champion) .. 1110 (Star) при общей ширине 900. Поэтому бюджет высоты нельзя перевести
// в ширину одним общим числом — пропорция приходит параметром от конкретного мокапа.

// Тот же нижний потолок, что и у `_displayWidth` на телефоне: уже 150 px форма перестаёт
// быть различимой, и лучше отдать прокрутку, чем нечитаемый холст.
export const MIN_DISPLAY_WIDTH = 150;

/**
 * Ширина холста с учётом бюджета высоты.
 *
 * @param {number} displayWidth ширина, выбранная по горизонтали (`_displayWidth`)
 * @param {number} aspect пропорция мокапа: высота / ширина (992/900 у Champion)
 * @param {number} availHeight сколько пикселей высоты отдано под холст
 * @returns {number} ширина, при которой `ширина * aspect` уже влезает в `availHeight`
 */
export function capWidthByHeight(displayWidth, aspect, availHeight) {
  if (!(aspect > 0)) return displayWidth; // пропорция ещё не известна — не портим ширину
  const byHeight = Math.floor(availHeight / aspect);
  return Math.max(MIN_DISPLAY_WIDTH, Math.min(displayWidth, byHeight));
}
