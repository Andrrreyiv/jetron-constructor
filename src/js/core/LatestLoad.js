// «Побеждает последняя запрошенная загрузка», а не последняя приехавшая.
//
// Замер 04.09 (headless, случайная задержка мокапов 300..2500 мс, клик по цвету каждые 250 мс):
// после PR #15 пять переключений расцветки из десяти оставляли на холсте ЧУЖОЙ мокап. На коде
// ДО PR #15 — 0 из 10. Разница не в загрузке, а в том, куда она попадает: раньше каждая смена
// расцветки пересобирала холсты, и опоздавшая картинка ложилась на ВЫБРОШЕННЫЙ холст; PR #15
// холст переиспользует (без этого «блоки скакали» — см. ViewsRebuild.js), и та же опоздавшая
// картинка теперь затирает актуальную.
//
// ⚠️ Отменять переиспользование нельзя — вернётся жалоба клиента 03.09. Поэтому помечаем каждую
// загрузку номером и применяем только последнюю.
// ⚠️ Счётчик у КАЖДОГО холста свой: у некомпозитных форм холста два (перёд и спина), и загрузка
// спины не должна отменять загрузку переда.
export function создатьСчётчикЗагрузок() {
  let последняя = 0;
  return {
    начать: () => ++последняя,
    актуальна: (n) => n === последняя,
  };
}
