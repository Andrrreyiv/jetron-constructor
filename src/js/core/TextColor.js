// Цвет надписей: кто у кого его берёт.
//
// Клиент 30.08: «привяжи пожалуйста цвет номера на груди к цвету надписей на спине,
// чтобы они одинакового цвета были». У номера на груди своего выбора цвета нет и не
// появится — он ведомый: своей палитры в карточке груди клиенту не показывают.

// Клиент 31.08 письменно: «Шрифт номера на груди, привязать к шрифту на спине».
// Тот же дефект и то же лечение, что было с цветом 30.08.

// Спина — единственная опция вида `name_number`: фамилия и номер рисуются одним цветом.
export function linkedNumberColor(options, optCache, fallback) {
  const спина = (options || []).find(o => o && o.kind === 'name_number');
  const c = спина && optCache && optCache[спина.id];
  return (c && c.color) || fallback;
}

// Шрифт ведомый по той же причине: своего выбора шрифта у номера на груди нет.
export function linkedNumberFont(options, optCache, fallback) {
  const спина = (options || []).find(o => o && o.kind === 'name_number');
  const c = спина && optCache && optCache[спина.id];
  return (c && c.fontId) || fallback;
}

// Мало взять значение у спины — надо ещё перерисовать УЖЕ нарисованный ведомый номер.
// Иначе привязка срабатывает только при следующем вводе в его поле, а на экране выглядит
// как её отсутствие: замер 01.09 в браузере показал спину `stalinist` при груди `rpl`.
// ⚠️ Правку 30.08 делали по цвету, и условие перерисовки осталось про ОДИН цвет; шрифт
// 31.08 добавили в значения, а сюда — нет. Список ведущих полей теперь один на оба.
// Ввод самой фамилии или номера на спине ведомых не касается: их значения от него не зависят.
export const ВЕДУЩИЕ_ПОЛЯ = ['color', 'fontId'];

export function ведомыеПерерисовать(patch) {
  return ВЕДУЩИЕ_ПОЛЯ.some((поле) => поле in (patch || {}));
}

// ── Яркость ткани под бренд-знаком ────────────────────────────────────────────
// Клиент 04.09: «логотип на груди чёрный, предвижу необходимость настройки цвета».
// Правило «тёмная ткань → белый знак» существовало и раньше, врал ЗАМЕР яркости.
// Две замеренные причины, обе лечит эта функция:
//   1. Мокап лежит на чистом БЕЛОМ листе, а бокс знака одинаков для всех 44 расцветок
//      и часто свисает с формы. На красном Winner 36 % выборки было фоном: среднее 156.5
//      вместо 102 у самой ткани → чёрный знак на красной футболке. Худшее — шорты:
//      жёлтые 178 против 37, сиреневые 168 против 36, лаймовые 184 против 40.
//   2. Среднее врёт на ДВУХЦВЕТНОЙ ткани. На champion-white знак стоит на границе
//      бордового и белого: среднее 128.8 при пороге 128 — монетка. Медиана берёт то,
//      чего под знаком больше.
export const ФОН_БЕЛЫЙ = 250;   // все три канала ≥ этого — лист мокапа, а не ткань
export const ДОЛЯ_ТКАНИ = 0.25; // меньше — знак стоит мимо формы: это вопрос ПОЗИЦИИ, не цвета

export function яркостьТкани(rgba) {
  if (!rgba || !rgba.length) return null;
  const все = [], ткань = [];
  for (let i = 0; i + 3 < rgba.length; i += 4) {
    const r = rgba[i], g = rgba[i + 1], b = rgba[i + 2];
    const l = 0.299 * r + 0.587 * g + 0.114 * b;
    все.push(l);
    if (!(r >= ФОН_БЕЛЫЙ && g >= ФОН_БЕЛЫЙ && b >= ФОН_БЕЛЫЙ)) ткань.push(l);
  }
  if (!все.length) return null;
  // Ткани меньше четверти — отбрасывать фон не по чему, отвечаем по всей выборке.
  const набор = ткань.length >= все.length * ДОЛЯ_ТКАНИ ? ткань : все;
  набор.sort((a, b) => a - b);
  return набор[Math.floor(набор.length / 2)];
}

// Порог и решение держим отдельно от замера: ручная настройка цвета, которую просит клиент,
// придёт сюда. Яркость неизвестна (нет подложки) — поведение прежнее, чёрный знак.
export const ПОРОГ_ТЁМНОЙ = 128;

export function знакБелый(яркость) {
  return яркость != null && яркость < ПОРОГ_ТЁМНОЙ;
}
