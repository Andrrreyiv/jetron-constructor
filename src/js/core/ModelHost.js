// Узел карусели эскизов появился в `index.html` 31.08, когда палитра и модели разъехались
// по разным местам раскладки. С тех пор `buildColorPicker()` начинался строкой
// `if (!palHost || !modHost) return;` — отсутствие узла эскизов молча гасило и палитру.
//
// Замер на боевом 06.09, сразу после выкладки: файлы на сервере верные (sha256 боевого
// index.html совпал с нашим побайтово, `#modelpick` в нём есть), а вкладка рисовала конструктор
// БЕЗ ЕДИНОГО свотча — 0 кнопок `.pcolor` вместо 15, ошибок в консоли ноль. Причина не в
// выкладке: `/constructor/` отдаётся вообще без `cache-control`, только с ETag, поэтому браузер
// держит HTML по эвристике (~10 % возраста файла, у нас это дни). Вернувшийся покупатель
// получает СТАРУЮ разметку со СВЕЖИМ скриптом, а в старой разметке `#modelpick` ещё нет.
//
// Поэтому узел создаём, а не требуем: это чинит любое рассогласование «старый HTML + новый JS».
// Раскладку созданному узлу задаёт grid `#stage` по идентификатору и классу, как и разметочному.
export function обеспечитьУзелМоделей(palHost, doc) {
  const документ = doc || (typeof document !== 'undefined' ? document : null);
  if (!документ) return null;

  const готовый = документ.getElementById('modelpick');
  if (готовый) return готовый;

  // Без палитры вставлять некуда: место узла задаётся относительно неё.
  if (!palHost || !palHost.parentNode) return null;

  const узел = документ.createElement('div');
  узел.id = 'modelpick';
  узел.className = 'modelpick';
  // ⚠️ Строго СРАЗУ ПОСЛЕ палитры: на раскладке ≤900 палитра и эскизы идут отдельными строками
  // под формой именно в этом порядке, а `_availHeight()` меряет высоту эскизов, обрезая холст.
  palHost.parentNode.insertBefore(узел, palHost.nextSibling);
  return узел;
}
