// Нужно ли пересобирать холсты — или прежние подходят как есть.
//
// Клиент 03.09: «Когда цвет выбираем, блоки начинают скакать». Смена расцветки шла через
// безусловный `buildViews()`, а он делает `viewsEl.innerHTML = ''` и создаёт холсты заново.
// Цена этого на КАЖДОМ клике по цвету (замер headless, торможение картинок 300 мс):
//   • плашка линейки с кнопками «Скачать макет» и «В КАРТОЧКУ» пропадала на 305-321 мс;
//   • новый холст рождался 600×800 (`_displayWidth(1)` = 600, высота по дефолту 1200/900)
//     внутри карточки 501×465 и тянул раскладку — карточка уезжала вверх 83 → 69 px;
//   • карточка стояла пустой, пока грузился новый WebP.
// PR #13 до этого починил только РАЗМЕР карточки (`_applyCardSize` до `await`), мигание
// содержимого он не трогал.
//
// Почему переиспользование холста решает всё три сразу: `CanvasView.setBackground()`
// присваивает `canvas.backgroundImage` уже ПОСЛЕ `await fabric.FabricImage.fromURL(...)`,
// то есть старая картинка висит на экране до готовности новой. Пустоты не возникает,
// плашку никто не удаляет, переростка 600×800 не появляется.
//
// ⚠️ Пересобирать всё же ОБЯЗАТЕЛЬНО, когда меняется что-то из трёх: состав видов (композит
// «всё на одной картинке» ↔ отдельные перёд/спина — у формы может появиться или пропасть вид),
// ширина холста (поворот телефона, ресайз) и бюджет высоты. Первые две уже ловились раньше
// молча — просто потому, что пересборка была всегда.
//
// ⚠️ Переиспользование безопасно по состоянию: `renderZones()` начинается с `clearAll()`,
// который снимает с холста все рамки зон, размещения покупателя и служебные надписи бренда.
// Ничего от прежней расцветки не переживает перерисовку.

/**
 * @param {{key:string, displayWidth:number, maxHeight:number}|null} prev план прошлой сборки
 * @param {{key:string, displayWidth:number, maxHeight:number}} next план запрошенной сборки
 * @returns {boolean} true — пересобирать холсты, false — прежние подходят
 */
export function needsViewsRebuild(prev, next) {
  if (!prev || !next) return true;
  return prev.key !== next.key
    || prev.displayWidth !== next.displayWidth
    || prev.maxHeight !== next.maxHeight;
}
