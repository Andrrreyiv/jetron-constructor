// Куда ведёт кнопка на плашке над макетом.
// Клиент 28.08: кнопка называется «перейти в карточку» и открывает карточку ИМЕННО той
// расцветки, что сейчас на экране, а не раздел каталога по линейке.

// Клиент 01.09: «поменяйте "перейти в карточку" на "в карточку"». Это не только вкус:
// на телефоне длинная подпись ломалась на ТРИ строки и плашка над макетом вырастала
// до 100+ px, съедая картинку (его скриншот 15:05). Смысл «переход» остаётся за стрелкой.
const ПОДПИСЬ = 'в карточку →';

// Запасной путь «в раздел линейки» отменён 2026-09-07: замер боевого показал, что все восемь
// адресов /product-category/<линейка>/ отдают 404 — такого раздела на сайте нет вовсе.
// Клиент голосом: «кнопка перейти в карточку, но не работает, пишет, что страница не найдена».
// Нет адреса карточки — нет кнопки: молчащая кнопка честнее битой.
export function productLink(form) {
  const card = String((form && form.productUrl) || '').trim();
  return card ? { href: card, isCard: true, label: ПОДПИСЬ } : null;
}
