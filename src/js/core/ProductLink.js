// Куда ведёт кнопка на плашке над макетом.
// Клиент 28.08: кнопка называется «перейти в карточку» и открывает карточку ИМЕННО той
// расцветки, что сейчас на экране, а не раздел каталога по линейке.

// Подпись у кнопки ОДНА на оба случая. Клиент 31.08 (11:06): «изначально я вам писал кнопку
// в карточку, надо обратно вернуть в карточку… пускай люди знают, что это переход в карточку».
// Раньше запасной путь подписывался «в каталог», чтобы не обещать карточку, которой нет.
// Отменено сознательно, а не забыто: на боевом адрес приходит из WooCommerce на каждую
// расцветку, и в раздел линейки уводит только то, чего в каталоге нет вовсе (демо целиком,
// чёрный Star). Оговорка про демо вписана в письмо №13 — чинить обратно не надо.
const ПОДПИСЬ = 'перейти в карточку →';

export function productLink(form, catalog) {
  const card = String((form && form.productUrl) || '').trim();
  if (card) return { href: card, isCard: true, label: ПОДПИСЬ };

  // `isCard` остаётся честным и здесь: подпись — то, что видит покупатель, флаг — то, что
  // знает код. Смешивать их нельзя, на флаге завязана логика, а не текст.
  const c = catalog || {};
  const line = (form && form.line) || '';
  if (!line) return null;
  const slug = (c.lineSlugs && c.lineSlugs[line]) || line.toLowerCase();
  return { href: (c.base || '/shop/') + slug + (c.suffix || ''), isCard: false, label: ПОДПИСЬ };
}
