// Авто-фит текста в зону (ТЗ): одна цифра занимает высоту зоны;
// при 2+ символах шрифт ужимается, чтобы строка влезла по ширине.
// charWidthRatio 0.75: заглавные кириллические буквы (ИВАНОВ, СИДОРОВ) в среднем ~0.71em
// ширины — при 0.6 фамилия сползала за рамку (клиент 2026-07-17: «кажется, вылезает по бокам»).
export function fitFontSize({ text, rect, charWidthRatio = 0.75 }) {
  const n = [...String(text)].length;
  const byHeight = rect.height;
  if (n <= 1) return byHeight;
  const byWidth = rect.width / (n * charWidthRatio);
  return Math.min(byHeight, byWidth);
}

// Точная подгонка текста под рамку по фактическим размерам глифов Fabric.
// fitFontSize даёт лишь грубую оценку по средней ширине символа (charWidthRatio):
// для цифр она завышала ширину, из-за чего между последним символом и краем рамки
// оставался большой фиксированный зазор (клиент 2026-07-22: «от цифры до правого
// поля огромное расстояние и оно всегда зафиксировано»). Здесь измеряем реальную
// ширину/высоту строки при опорном кегле и масштабируем так, чтобы текст вплотную
// заполнил рамку по ограничивающей стороне — без пустого отступа.
// obj — текстовый объект Fabric (fabric.IText); мутирует его fontSize, возвращает кегль.
export function fitTextToRect(obj, rect, { ref = 100 } = {}) {
  obj.set({ fontSize: ref });
  if (typeof obj.initDimensions === 'function') obj.initDimensions();
  const w = obj.width || 1;
  const h = obj.height || ref;
  const size = Math.max(1, ref * Math.min(rect.width / w, rect.height / h));
  obj.set({ fontSize: size });
  if (typeof obj.initDimensions === 'function') obj.initDimensions();
  return size;
}

// ── Посадка номера по «чернилам» глифа (клиент 2026-07-24) ──────────────────────────
// Fabric меряет текст КОРОБКОЙ: obj.height = 1.13×кегль (межстрочная плюс выносные элементы),
// obj.width включает боковые полуапроши. Видимая цифра занимает лишь часть этой коробки —
// замер на зоне номера 171×156 (шрифт РПЛ): «2» закрывала 36% ширины и 60% высоты рамки,
// «23» — 73%/61%. Отсюда жалоба заказчика «номер не прилипает к стенкам рамки»: подгонка по
// коробке физически не может прижать глиф к кромке. Прежний обход — стретч до 1.15 — лишь
// маскировал зазор и деформировал цифру, что заказчик отдельно запретил («деформировать не надо»).
// Поэтому номер считаем по фактическим чернилам (measureText.actualBoundingBox*), а не по коробке.
export const FABRIC_BOX_RATIO = 1.13;      // obj.height / кегль у однострочного текста Fabric v6
export const FABRIC_BASELINE_RATIO = 0.89; // базовая линия ниже верха коробки на 0.89×кегля

// Отступ чернил от верхней кромки зоны номера (заказчик 2026-08-27: «цифры 8 и 7 опустить
// на 1 пиксель вниз»). Прижатие к кромке геометрически одинаково у всех цифр — заметно оно
// только у 7 и 8, у которых верх плоский; у скруглённых 0/6/9 глаз видит зазор там, где его нет.
// Отступ поэтому единый: дай его двум цифрам — и «78» встанет ступенькой относительно «12».
// Задан ДОЛЕЙ высоты зоны, а не пикселями: холст пересчитывается под контейнер (замер 27.08 —
// логическая ширина 597 при displayWidth 450 в конфиге), поэтому «пиксель» на десктопе, на
// телефоне и в макете печати — три разные величины. Доля же даёт один и тот же отступ везде.
//
// 🔴 31.08 клиент отменил этот отступ голосовым: «цифра должна касаться верхнего края рамки
// и нижнего края рамки, то есть там отступ один пиксель или 0 пиксель… сделать 0, а если
// не будет обрезаться, то так оставляем. Если будет всё-таки обрезаться на 0, тогда сделайте
// 1 пиксель». Проверено в браузере — не обрезается, поэтому ровно ноль. Возвращать сюда
// 0.02 нельзя: ту просьбу 27.08 он сам же снял. Если когда-нибудь понадобится ровно 1 пиксель,
// это `1 / 1200` (эталонная высота холста), а не пиксельная константа.
export const NUMBER_TOP_INSET_RATIO = 0;

// Кегль, при котором чернила вписаны в рамку БЕЗ деформации: упираемся в ограничивающую сторону,
// вторая остаётся с запасом (заказчик: «23» упирается по бокам в стенки, какого размера будет —
// такого и будет). ink — метрики чернил при кегле ref: { width, ascent, descent }.
// topInset отнимается от доступной высоты: иначе цифра, опущенная на отступ, вылезет
// за нижнюю кромку зоны ровно на его величину.
export function fitInkToRect(rect, ink, { ref = 100, topInset = 0 } = {}) {
  const inkW = Math.max(1, ink.width);
  const inkH = Math.max(1, ink.ascent + ink.descent);
  const availH = Math.max(1, rect.height - topInset);
  const fontSize = Math.max(1, ref * Math.min(rect.width / inkW, availH / inkH));
  return { fontSize };
}

// Центр коробки Fabric (originX/originY = center), при котором чернила прижаты к ВЕРХНЕЙ кромке
// рамки (заказчик 2026-07-24: «лучше всего к верхней части притянуть») и центрированы по ширине.
// m — размеры при итоговом кегле: boxWidth/boxHeight — коробка Fabric, inkWidth/inkAscent — чернила,
// inkLeftOffset — отступ чернил от левого края коробки (= -actualBoundingBoxLeft).
export function inkAlignedCenter(rect, m) {
  return {
    centerX: rect.left + rect.width / 2 - m.inkLeftOffset - m.inkWidth / 2 + m.boxWidth / 2,
    centerY: rect.top + (m.topInset || 0) + m.inkAscent - FABRIC_BASELINE_RATIO * m.fontSize + m.boxHeight / 2
  };
}

// Номерные зоны (back_number/chest_number/shorts_number): сажаются по чернилам с прижатием к верху.
// Прочий текст (фамилия/надписи) — прежней подгонкой по коробке, заказчик по ним замечаний не давал.
export function isNumberZone(key) { return /(^|_)number$/.test(String(key || '')); }

export function zoneToRect(box, canvas) {
  return {
    left: box.x * canvas.width,
    top: box.y * canvas.height,
    width: box.w * canvas.width,
    height: box.h * canvas.height
  };
}
