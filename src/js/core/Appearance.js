// Внешний вид сцены: фон, рамки и отступы, которыми управляет админка.
//
// Клиент 13.09 голосовым: «может вы мне скажете просто, где настраиваются вот эти все параметры…
// я попробую сам подвигать, так быстрее». До этого дня честный ответ был «нигде»: значения жили
// числами в `stand.css`. Теперь они токены, а тут — правила, по которым админка их меняет.
//
// 🔴 Главное правило то же, что у остальных разделов admin.json: битое значение НЕ должно ронять
// вёрстку. Проверяем каждое поле поштучно и молча выбрасываем негодное, оставаясь на CSS-умолчании.
// Пустой раздел означает «ничего не переопределяем», а не «сбрось всё в ноль».

import { корректныйЦвет } from './TextColor.js';

// Единый список полей: по нему строится и форма в админке, и применение на стенде.
// Разъедутся — появится поле, которое админ меняет, а покупатель не видит.
export const ПОЛЯ_ВИДА = Object.freeze([
  { ключ: 'stageBg', css: '--stage-bg', тип: 'цвет', подпись: 'Фон сцены', умолчание: '#ffffff' },
  { ключ: 'stageBorder', css: '--stage-border', тип: 'цвет', подпись: 'Рамка сцены', умолчание: '#ece3d0' },
  { ключ: 'cardBg', css: '--card-bg', тип: 'цвет', подпись: 'Фон карточки формы', умолчание: 'transparent' },
  { ключ: 'cardBorder', css: '--card-border', тип: 'цвет', подпись: 'Рамка карточки формы', умолчание: 'transparent' },
  { ключ: 'padTop', css: '--stage-pad-top', тип: 'px', подпись: 'Отступ сверху', умолчание: 40 },
  { ключ: 'padSide', css: '--stage-pad-side', тип: 'px', подпись: 'Отступы по бокам', умолчание: 32 },
  { ключ: 'padBottom', css: '--stage-pad-bottom', тип: 'px', подпись: 'Отступ снизу', умолчание: 28 },
]);

// Потолок отступа. 200 px — это уже половина высоты холста на ноутбуке; выше держать незачем,
// а случайный лишний ноль («400») увёл бы форму за нижний край.
export const ПРЕДЕЛ_ОТСТУПА = 200;

// Правило «что такое корректный цвет» живёт в TextColor.js и переиспользуется, а не копируется:
// две копии одной проверки разъезжаются, и тогда админка примет то, что не примет редактор зон.
// Здесь только надстройка: фону и рамке, в отличие от знака, разрешено быть прозрачными.
export function корректныйЦветВида(v) {
  if (typeof v !== 'string') return false;
  const t = v.trim();
  return t === 'transparent' || корректныйЦвет(t);
}

export function корректныйОтступ(v) {
  const n = typeof v === 'string' && v.trim() !== '' ? Number(v) : v;
  return typeof n === 'number' && Number.isFinite(n) && Number.isInteger(n)
    && n >= 0 && n <= ПРЕДЕЛ_ОТСТУПА;
}

/**
 * Оставляет только поля, которые можно применить. Всё остальное выбрасывается молча:
 * на экране это выглядит как «настройка не подействовала», и это лучше поехавшей вёрстки.
 */
export function проверитьВид(вид) {
  const out = {};
  if (!вид || typeof вид !== 'object') return out;
  for (const поле of ПОЛЯ_ВИДА) {
    const v = вид[поле.ключ];
    if (v === undefined || v === null || v === '') continue;
    if (поле.тип === 'цвет' && корректныйЦветВида(v)) out[поле.ключ] = String(v).trim().toLowerCase();
    if (поле.тип === 'px' && корректныйОтступ(v)) out[поле.ключ] = Number(v);
  }
  // Тень карточки — отдельный тумблер, а не цвет: у неё два осмысленных состояния.
  if (typeof вид.cardShadow === 'boolean') out.cardShadow = вид.cardShadow;
  return out;
}

/**
 * Что именно выставить в `document.documentElement.style`.
 * Возвращает ТОЛЬКО заданные поля: не заданное обязано остаться на умолчании из `stand.css`,
 * иначе админка начнёт диктовать значения, которых в ней не трогали.
 */
export function видВПеременные(вид) {
  const чистый = проверитьВид(вид);
  const vars = {};
  for (const поле of ПОЛЯ_ВИДА) {
    if (!(поле.ключ in чистый)) continue;
    vars[поле.css] = поле.тип === 'px' ? `${чистый[поле.ключ]}px` : чистый[поле.ключ];
  }
  if ('cardShadow' in чистый) {
    // Имя токена, а не готовая тень: сама тень остаётся описанной в CSS одним местом.
    vars['--card-shadow'] = чистый.cardShadow ? 'var(--sh-md)' : 'none';
    vars['--card-shadow-hover'] = чистый.cardShadow ? 'var(--sh-lg, var(--sh-md))' : 'none';
  }
  return vars;
}

/**
 * Применение на стенде. Вынесено сюда, а не в main.browser.js, чтобы правило «пустое поле
 * не трогает CSS» было одно и проверялось тестом.
 */
export function применитьВид(вид, корень) {
  const узел = корень || (typeof document !== 'undefined' ? document.documentElement : null);
  if (!узел || !узел.style) return {};
  const vars = видВПеременные(вид);
  for (const [имя, значение] of Object.entries(vars)) узел.style.setProperty(имя, значение);
  return vars;
}
