// Какие размерные категории предлагать покупателю на этой расцветке.
//
// Клиент 09.09: «90% покупателей берут детскую форму, зачем им сразу показывать завышенную
// цену? Если он нажал на чемпион, зачем показывать взрослую цену, если её у нас в природе нет».
// Замер боевого 09.09 подтвердил: у Champion все 6 позиций каталога детские, у Фаворита
// взрослых только Зелёный и Сиреневый. До этой правки конструктор предлагал взрослый размер
// везде и брал на него запасную цену из конфига — 1280 вместо настоящих 1680.
//
// Граница проходит по ЛИНЕЙКЕ, а не по расцветке: голосовым того же дня клиент велел оставить
// взрослого Фаворита на всех пяти расцветках по 1680 («цены приравниваем к фактическим»),
// потому что взрослый Фаворит существует и просто не доведён в каталоге. Взрослого Чемпиона
// не существует вовсе — вот его и не показываем.

import { resolveLinePrice } from './CatalogPrices.js';

/**
 * Порядок как на экране. Клиент 09.09 (голосовое 08:42): «детскую передвигаем влево,
 * взрослую вправо» — её берут 90 % покупателей, ей и стоять первой.
 * Порядок несёт и второй смысл: `normalizeAge()` при недоступном выборе берёт первый
 * из списка, то есть детскую — тот же ответ, что и `ВОЗРАСТ_ПО_УМОЛЧАНИЮ`.
 */
export const ВОЗРАСТЫ = ['child', 'adult'];

/** Клиент 09.09: «90% покупателей берут детскую форму». Конструктор открывается на ней. */
export const ВОЗРАСТ_ПО_УМОЛЧАНИЮ = 'child';

/**
 * Удержать выбор возраста в границах доступного. Человек выбрал взрослую на Легенде и перешёл
 * на Чемпиона — оставить выбор нельзя, взрослого Чемпиона не существует. Пустой список значит
 * «считать нечем», тогда выбор не трогаем вовсе.
 */
export function normalizeAge(current, options) {
  const список = Array.isArray(options) ? options : [];
  if (!список.length) return current;
  return список.includes(current) ? current : список[0];
}

/**
 * Возрасты, которые реально можно купить. Смотрим по ЛИНЕЙКЕ, а не по расцветке: у белого
 * Фаворита взрослой позиции в каталоге нет, но взрослый Фаворит как товар существует
 * (заведён на сиреневом и зелёном) — прятать его нельзя, клиент 09.09 прямо велел оставить
 * его по цене линейки. А взрослого Чемпиона нет ни в одной из шести расцветок, и вот его
 * предлагать не за чем: «зачем показывать взрослую цену, если её у нас в природе нет».
 *
 * Каталог — источник правды, но только когда он есть: на демо-стенде и при сбое сети индекс
 * пустой, и тогда мы обязаны оставить обе категории, иначе стенд остался бы без кнопок.
 * Линейка, которой нет в каталоге вовсе (новая), тоже получает обе: запереть покупателя
 * без единой кнопки хуже, чем показать обе с запасной ценой, как было всегда.
 */
export function ageOptions(index, { line } = {}) {
  if (!index || typeof index.get !== 'function' || !index.size) return [...ВОЗРАСТЫ];
  const есть = ВОЗРАСТЫ.filter((ageCategory) => resolveLinePrice(index, { line, ageCategory }) != null);
  return есть.length ? есть : [...ВОЗРАСТЫ];
}
