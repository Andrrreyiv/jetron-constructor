// Замер 04.09 (headless, случайная задержка мокапов 300..2500 мс, переключение цвета через
// 250 мс): после PR #15 пять переключений из десяти оставляли на холсте ЧУЖОЙ мокап —
// покупатель выбрал сиреневую, а видит салатовую, и так до следующего клика по цвету.
// На коде ДО PR #15 тот же замер дал 0 из 10.
//
// Почему сломалось именно там. `setBackground()` присваивает `canvas.backgroundImage` ПОСЛЕ
// `await fabric.FabricImage.fromURL(...)`. Раньше каждая смена расцветки пересобирала холсты,
// и опоздавшая картинка ложилась на ВЫБРОШЕННЫЙ холст — вреда не было. PR #15 холст
// переиспользует (и правильно делает: без него «блоки скакали»), поэтому опоздавшая картинка
// теперь затирает актуальную. Порядок ответов не гарантирован ничем: файлы разного веса.
//
// Лечение — не отменять переиспользование, а помечать загрузки номером и применять только
// последнюю. Сам счётчик держим отдельной чистой функцией: в canvas.browser.js его не проверить,
// там Fabric и DOM.

import test from 'node:test';
import assert from 'node:assert/strict';

import { создатьСчётчикЗагрузок } from '../src/js/core/LatestLoad.js';

test('применяется только последняя начатая загрузка, даже если она ответила первой', () => {
  const счёт = создатьСчётчикЗагрузок();

  // Покупатель кликнул «салатовая», через 250 мс передумал и кликнул «сиреневая».
  const салатовая = счёт.начать();
  const сиреневая = счёт.начать();

  // Сиреневая ответила первой — она последняя запрошенная, её и ставим.
  assert.equal(счёт.актуальна(сиреневая), true);
  // Салатовая доехала позже. Раньше именно она и оставалась на экране.
  assert.equal(счёт.актуальна(салатовая), false);

  // Проверка актуальности ничего не меняет: повторный вопрос даёт тот же ответ.
  assert.equal(счёт.актуальна(сиреневая), true);

  // Следующий клик снова делает актуальной новую загрузку, а не воскрешает прежние.
  const красная = счёт.начать();
  assert.equal(счёт.актуальна(красная), true);
  assert.equal(счёт.актуальна(сиреневая), false);
});

test('счётчики разных холстов не мешают друг другу', () => {
  // Композитные формы рисуются на одном холсте, обычные — на двух (перёд и спина).
  // Номер загрузки одного холста не должен отменять загрузку соседнего.
  const перёд = создатьСчётчикЗагрузок();
  const спина = создатьСчётчикЗагрузок();
  const а = перёд.начать();
  const б = спина.начать();
  assert.equal(перёд.актуальна(а), true);
  assert.equal(спина.актуальна(б), true);
});
