# -*- coding: utf-8 -*-
"""Контракт машинной приёмки.

Приёмка — единственное, что стоит между «прогнали 34 файла» и «залили клиенту».
Если проверяльщик молча пропускает брак, зелёный отчёт хуже, чем никакого.
Поэтому тесты здесь кормят `report` заведомо битыми строками и требуют,
чтобы он ругнулся.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))

from run_normalize import report  # noqa: E402


def строка(**kw):
    """Строка отчёта про здоровый файл. Тест портит ровно одно поле."""
    r = {
        "line": "Winner",
        "target": "Winner белый",
        "src_box": (0, 0, 580, 1000),
        "scale": 1.15,
        "out_box": (160, 24, 740, 1176),
        "size": (900, 1200),
        "bytes": 120 * 1024,
    }
    r.update(kw)
    return r


class TestReport:
    def test_ловит_съехавший_центр(self, tmp_path):
        """Форма обязана стоять по центру во всех кадрах. Зоны заданы долями
        ширины ХОЛСТА, а не формы: уехал центр — уехали логотипы и номер.
        Ширина при этом законно гуляет, пропорция формы 0.48..0.62."""
        bad = report(
            [
                строка(out_box=(160, 24, 740, 1176)),
                строка(target="Winner синий", out_box=(300, 24, 880, 1176)),
            ],
            [],
            tmp_path / "отчёт.md",
        )
        assert any("центр" in b for b in bad), bad

    def test_ловит_перевес(self, tmp_path):
        """Вес не косметика: все 45 мокапов грузятся в конструкторе с телефона.

        Порог 600 КБ был взят от старого PNG-набора. После перехода на WebP
        (28.08) партия упала с 29 МБ до 3.3 МБ, а самый тяжёлый файл — до 130 КБ,
        и порог в 600 КБ не сработал бы уже никогда: сторож молча перестал бы
        сторожить, а зелёная приёмка тогда хуже, чем никакой.

        Держим порог у реального потолка партии с запасом примерно в полтора раза.
        """
        bad = report([строка(bytes=250 * 1024)], [], tmp_path / "отчёт.md")
        assert any("вес" in b for b in bad), bad
