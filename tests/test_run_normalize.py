# -*- coding: utf-8 -*-
"""Контракт машинной приёмки.

Приёмка — единственное, что стоит между «прогнали 45 файлов» и «залили клиенту».
Если проверяльщик молча пропускает брак, зелёный отчёт хуже, чем никакого.
Поэтому тесты здесь кормят `report` заведомо битыми строками и требуют,
чтобы он ругнулся.

⚠️ Инварианты проверяются ВНУТРИ линейки, а не по всем 45 сразу. Кадр считается
на линейку (`line_canvas`), поэтому «размер у всех одинаковый» и «высота рамки
у всех одинаковая» — уже НЕ инварианты, и требовать их значит валить здоровую партию.
"""
import json
import sys
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))

from normalize_mockups import BOTTOM_PX, CANVAS_WIDTH, TOP_PX  # noqa: E402
from run_normalize import report, run  # noqa: E402

# Кадр здоровой линейки: самая высокая форма 854 px + верх 216 + низ 40.
ВЫСОКАЯ = 854
КАДР = (CANVAS_WIDTH, ВЫСОКАЯ + TOP_PX + BOTTOM_PX)


def строка(**kw):
    """Строка отчёта про здоровый файл. Тест портит ровно одно поле.

    Это самая высокая расцветка линейки: её нижний зазор равен `BOTTOM_PX`
    ровно, потому что именно она задала высоту кадра.
    """
    r = {
        "line": "Winner",
        "target": "Winner белый",
        "src_box": (0, 0, 580, 1000),
        "scale": 1.15,
        "out_box": (160, TOP_PX, 740, TOP_PX + ВЫСОКАЯ - 1),
        "size": КАДР,
        "canvas": КАДР,
        "bytes": 120 * 1024,
    }
    r.update(kw)
    return r


def низкая(**kw):
    """Расцветка той же линейки с формой ниже на 100 px.

    Разброс высот внутри линейки законен: это зазор поставщика между передом
    и задом и то, сколько попало гетр и бутс. Равнять высоту значило бы
    искажать пропорцию формы у одних ради других.
    """
    kw.setdefault("out_box", (160, TOP_PX, 740, TOP_PX + ВЫСОКАЯ - 101))
    return строка(target="Winner синий", **kw)


def _исходник(path, ширина_формы, высота_формы, поле=60):
    """Синтетический кадр поставщика: чёрный прямоугольник на белом поле."""
    im = Image.new("RGB", (ширина_формы + поле * 2, высота_формы + поле * 2), (255, 255, 255))
    im.paste(Image.new("RGB", (ширина_формы, высота_формы), (10, 10, 10)), (поле, поле))
    im.save(path)


def партия(tmp_path):
    """Две линейки: у Winner формы разной высоты, у Champion своя, ниже обеих."""
    src = tmp_path / "исходники"
    src.mkdir()
    _исходник(src / "высокая.png", 600, 900)
    _исходник(src / "низкая.png", 600, 700)
    _исходник(src / "чужая.png", 600, 500)
    карта = {
        "_source_dir": str(src),
        "lines": {
            "Winner": {"files": {"высокая.png": "Winner белый", "низкая.png": "Winner синий"}},
            "Champion": {"files": {"чужая.png": "Champion белый"}},
        },
    }
    путь = tmp_path / "карта.json"
    путь.write_text(json.dumps(карта, ensure_ascii=False), encoding="utf-8")
    return путь


class TestReport:
    def test_ловит_съехавший_центр(self, tmp_path):
        """Форма обязана стоять по центру во всех кадрах линейки. Зоны заданы
        долями ширины ХОЛСТА, а не формы: уехал центр — уехали логотипы и номер.
        Ширина при этом законно гуляет, пропорция формы 0.48..0.62."""
        bad = report(
            [строка(), низкая(out_box=(300, TOP_PX, 880, TOP_PX + ВЫСОКАЯ - 101))],
            [],
            tmp_path / "отчёт.md",
        )
        assert any("центр" in b for b in bad), bad

    def test_разная_высота_внутри_линейки_это_не_нарушение(self, tmp_path):
        """Здоровая партия обязана проходить молча.

        Высота рамки внутри линейки законно гуляет: это зазор поставщика между
        передом и задом и то, сколько попало гетр и бутс. Пока приёмка требует
        одинаковой высоты, она валит нормальные файлы, а зелёный отчёт, который
        нельзя получить на здоровой партии, никто читать не станет.
        """
        assert report([строка(), низкая()], [], tmp_path / "отчёт.md") == []

    def test_ловит_перевес(self, tmp_path):
        """Вес не косметика: все 45 мокапов грузятся в конструкторе с телефона.

        Порог 600 КБ был взят от старого PNG-набора. После перехода на WebP
        (28.08) партия упала с 29 МБ до 3.3 МБ, а самый тяжёлый файл — до 130 КБ,
        и порог в 600 КБ не сработал бы уже никогда: сторож молча перестал бы
        сторожить, а зелёная приёмка тогда хуже, чем никакой.
        """
        bad = report([строка(bytes=250 * 1024)], [], tmp_path / "отчёт.md")
        assert any("вес" in b for b in bad), bad


class TestRun:
    """Прогон целиком. Именно здесь ловится ошибка, из-за которой скрипт лежал:
    кадр нельзя посчитать в один проход, потому что он зависит от ВСЕХ файлов
    линейки, а не только от текущего."""

    def test_высота_кадра_идёт_от_самой_высокой_формы_линейки(self, tmp_path):
        """Winner: формы 900x600 и 700x600 при ширине кадра 900 дают вписанные
        высоты 1350 и 1050. Кадр обязан взять 1350, иначе высокая не влезет,
        а низкая получит ту самую белую полосу снизу."""
        rows, broken, bad = run(партия(tmp_path), tmp_path / "out", set(), tmp_path / "отчёт.md")
        assert broken == [], broken
        winner = {r["size"] for r in rows if r["line"] == "Winner"}
        assert winner == {(CANVAS_WIDTH, 1350 + TOP_PX + BOTTOM_PX)}, winner

    def test_линейки_меряются_порознь(self, tmp_path):
        """Champion ниже Winner, и кадр у него обязан быть свой.

        Общий кадр на все 45 вернул бы Champion белую полосу снизу — ровно то,
        из-за чего клиент и написал.
        """
        rows, _, _ = run(партия(tmp_path), tmp_path / "out", set(), tmp_path / "отчёт.md")
        кадры = {r["line"]: r["size"] for r in rows}
        assert кадры["Champion"][1] < кадры["Winner"][1], кадры

    def test_пропущенная_линейка_не_рендерится(self, tmp_path):
        """`--skip-lines` нужен, чтобы перегнать одну линейку, не трогая остальные.

        Пропущенная не должна ни попасть в отчёт, ни перезаписать свои файлы
        на диске: перегон «заодно» — это тихая правка того, что не просили.
        """
        rows, _, _ = run(партия(tmp_path), tmp_path / "out", {"Champion"}, tmp_path / "отчёт.md")
        assert {r["line"] for r in rows} == {"Winner"}, [r["target"] for r in rows]
        assert not list((tmp_path / "out").glob("Champion*"))

    def test_битый_файл_не_роняет_партию_и_виден_в_приёмке(self, tmp_path):
        """44 годных мокапа нужны, даже если 45-й не открылся.

        Но молча пропустить его нельзя: пропавший файл на боевом означает
        пустой холст у покупателя. Поэтому битый уходит в `broken`, оттуда
        в нарушения, и приёмка падает с кодом 1.
        """
        путь = партия(tmp_path)
        карта = json.loads(путь.read_text(encoding="utf-8"))
        (Path(карта["_source_dir"]) / "битая.png").write_bytes(b"not an image")
        карта["lines"]["Winner"]["files"]["битая.png"] = "Winner битый"
        путь.write_text(json.dumps(карта, ensure_ascii=False), encoding="utf-8")

        rows, broken, bad = run(путь, tmp_path / "out", set(), tmp_path / "отчёт.md")
        assert [n for n, _ in broken] == ["Winner битый"], broken
        assert any("битый файл" in b for b in bad), bad
        assert len(rows) == 3, [r["target"] for r in rows]

    def test_у_самой_высокой_формы_снизу_ровно_нижний_зазор(self, tmp_path):
        """Ради этого всё и затевалось: белой полосы под шортами больше нет.

        Раньше кадр добивался белым до 1200, и самая высокая форма линейки
        получала снизу 130..310 px пустоты. Теперь высоту кадра задаёт она сама,
        значит её нижний зазор обязан равняться `BOTTOM_PX` с точностью до
        округления при масштабировании.
        """
        rows, _, _ = run(партия(tmp_path), tmp_path / "out", set(), tmp_path / "отчёт.md")
        по_линейке = {}
        for r in rows:
            зазор = r["size"][1] - 1 - r["out_box"][3]
            по_линейке.setdefault(r["line"], []).append(зазор)
        # У КАЖДОЙ линейки есть расцветка, задавшая высоту кадра: её зазор и
        # проверяем. У остальных он больше — это их настоящая пропорция, а не
        # добивка белым.
        assert {l: min(g) for l, g in по_линейке.items()} == {
            "Winner": BOTTOM_PX,
            "Champion": BOTTOM_PX,
        }, по_линейке
