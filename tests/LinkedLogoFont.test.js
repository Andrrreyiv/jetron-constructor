// Текстовые «логотипы» берут шрифт и цвет у надписей на спине.
//
// Клиент 13.09 голосовым (расшифровка `docs/voice-client-2026-09-13-1629.txt`): «логотип
// на груди большой и логотип на спине под номером… их шрифты, ну и цвет тоже, и шрифт
// главное, нужно привязать к шрифту фамилией номер». На его снимке «ФК ПРАГМА» стоит
// рядом с «MATVEEV 7» другим шрифтом: обе опции `text_or_upload` брали общий дефолт
// (`this.defaultFontId()` и `this.textColor`) мимо выбора покупателя на спине.
//
// Тот же дефект уже лечили дважды у номера на груди: цвет 30.08, шрифт 31.08
// (`core/TextColor.js`). Здесь третий случай той же болезни.
//
// ⚠️ Привязка сделана ДЕФОЛТОМ, а не жёстко: `c.fontId ||` оставляет за покупателем свой
// выбор в карточке. Убрать `||` значит обесценить сам выбор шрифта в этой опции.
//
// ⚠️ Тест читает ИСХОДНИК: jsdom в проекте нет, браузерный слой иначе не проверить.
// Он ловит ровно тот способ сломать поведение, которым это уже ломали — возврат
// общего дефолта вместо ведомого значения.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const код = readFileSync(new URL('../src/js/ui/app.browser.js', import.meta.url), 'utf8');

// Ветка отрисовки `text_or_upload` внутри applyOption().
const ветка = код.match(/\} else \{ \/\/ text_or_upload([\s\S]*?)\n    \}/);

test('текстовый логотип рисуется ведомым шрифтом и цветом, а не общим дефолтом', () => {
  assert.ok(ветка, 'ветка text_or_upload должна существовать в applyOption()');
  assert.match(ветка[1], /_ведомыеОтСпины\(\)/,
    'шрифт и цвет берутся у спины через общий помощник');
  assert.match(ветка[1], /fontId: c\.fontId \|\| вед\.fontId/,
    'свой выбор покупателя сильнее ведомого значения');
  assert.match(ветка[1], /color: c\.color \|\| вед\.color/);
  assert.doesNotMatch(ветка[1], /fontId: c\.fontId \|\| this\.defaultFontId\(\)/,
    'общий дефолт мимо спины — ровно тот дефект, на который жаловался клиент');
});

// Помощник обязан быть один на отрисовку и на карточку: разъехавшись, они дадут
// подсвеченный в карточке шрифт, не совпадающий с нарисованным на макете.
test('ведомые значения считаются в одном месте и идут в карточку опции', () => {
  const помощник = код.match(/\n  _ведомыеОтСпины\(\)\s*\{([\s\S]*?)\n  \}/);
  assert.ok(помощник, 'метод _ведомыеОтСпины() должен быть определён');
  assert.match(помощник[1], /linkedNumberFont\(/);
  assert.match(помощник[1], /linkedNumberColor\(/);
  assert.match(код, /this\.fontColorHtml\(c, this\._ведомыеОтСпины\(\)/,
    'карточка логотипа подсвечивает то, что реально нарисовано');
  const карточка = код.match(/\n  fontColorHtml\(c[^)]*\)\s*\{([\s\S]*?)\n    \/\//);
  assert.match(карточка[1], /дефолты\.fontId/, 'подсветка учитывает унаследованный шрифт');
  assert.match(карточка[1], /дефолты\.color/);
});

// Замер 01.09 уже ловил это у номера на груди: привязка работала, но смена шрифта на спине
// не перерисовывала уже нарисованное, и на глаз выглядела как отсутствие привязки.
test('смена шрифта на спине перерисовывает и текстовые логотипы', () => {
  const цикл = код.match(/ведомыеПерерисовать\(patch\)\)\s*\{([\s\S]*?)\n    \}/);
  assert.ok(цикл, 'цикл перерисовки ведомых должен существовать');
  assert.match(цикл[1], /text_or_upload/,
    'текстовые логотипы попадают в перерисовку наравне с номером на груди');
  assert.match(цикл[1], /!свой\.image/,
    'загруженную картинку перерисовывать незачем: шрифт и цвет её не касаются');
});
