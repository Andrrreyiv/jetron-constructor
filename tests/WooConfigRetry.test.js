// Сорванная сеть на первом «в корзину» не должна запирать покупателя на «Заказ собран».
//
// `_wooConfig()` кэшировал ЛЮБОЙ исход, включая `null` от оборвавшегося запроса. Дальше
// `showOrder()` читает этот `null` как «WooCommerce тут нет» и рисует «Заказ собран: макет,
// файлы и надписи готовы к передаче» — покупатель уверен, что заказ ушёл, а корзина пуста.
// До перезагрузки страницы это уже не лечится: `undefined` в поле больше не появится.
//
// Класс `UniformApp` в Node не импортируется (`canvas.browser.js` тянет `fabric`, пакета
// в проекте нет), поэтому сторожим форму исходника — так же, как соседние тесты панели.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';

const код = fs.readFileSync(new URL('../src/js/ui/app.browser.js', import.meta.url), 'utf8');

const телоМетода = () => {
  const начало = код.indexOf('  async _wooConfig() {');
  assert.notEqual(начало, -1, 'метод _wooConfig() должен существовать');
  // Искать конец надо по НАЧАЛУ строки: голое '  }' попадает в середину «    } catch {»
  // и обрезает тело метода ровно перед той веткой, которую этот тест и сторожит.
  const конец = код.indexOf('\n  }', начало);
  assert.notEqual(конец, -1, 'у метода должен быть конец');
  return код.slice(начало, конец);
};

test('оборвавшийся запрос настроек WooCommerce не запоминается', () => {
  const тело = телоМетода();
  const catchОт = тело.indexOf('} catch');
  assert.notEqual(catchОт, -1, 'у запроса должна быть ветка catch');
  const ветка = тело.slice(catchОт);
  assert.ok(!ветка.includes('this._woo ='),
    'сорванный запрос кэшировать нельзя: до перезагрузки покупатель будет видеть «Заказ собран» вместо корзины');
  assert.ok(ветка.includes('return null'), 'вместо кэша просто отвечаем «настроек нет сейчас»');
});

test('удачный ответ и честный 404 запоминаются — не ходим за настройками на каждое нажатие', () => {
  const тело = телоМетода();
  assert.ok(тело.includes('if (this._woo !== undefined) return this._woo;'), 'кэш читается');
  assert.ok(тело.includes('this._woo = r.ok ? await r.json() : null;'),
    'ответ сервера — стабильный факт, его помним: и настройки, и «файла нет» на стенде без WooCommerce');
});
