// Сторож против ВОЗВРАТА подъёма белой рамки под курсором.
//
// Клиент 03.09 (третий из трёх комментариев, распознано с голоса):
//   «ролик мышку подвожу рамка поднимается и наоборот».
// Замер headless 04.09 подтвердил дословно, на ПК 1366×768:
//   мышь в стороне  → рамка на y=69, transform: none
//   мышь НА рамке   → рамка на y=65, transform: matrix(1,0,0,1,0,-4)
//   мышь убрали     → снова y=69
// То есть «поднимается» = ровно 4 px вверх, «и наоборот» = возврат. На телефоне 412×900
// сдвиг 0 — там :hover не срабатывает, и это сходится с тем, что жалоба про мышь.
//
// «Ролик» — колесо, и оно тоже проверено ОТДЕЛЬНО: курсор ставится в точку окна и БОЛЬШЕ
// НЕ ДВИГАЕТСЯ, крутится только колесо. Рамка проезжает под неподвижным курсором, и подъём
// включается и гаснет сам: -4 → 0 → 0 → 0 → 0 → 0 → -4. На боевом конструктор живёт как
// `<iframe>` на странице WP 3443, где прокрутка есть всегда, поэтому клиент ловит это
// каждым движением колеса, а не только когда целится мышью.
//
// ⚠️ Это ТА ЖЕ жалоба, что 01.09 («вот это гуляние рамки возможно убрать?»), по которой
// тогда убрали `transform: scale()` у `.pcolor` (комментарий в stand.css у той строки).
// Убрали один источник шевеления, а этот, самый крупный, остался.
//
// ⚠️ Тень при наведении ОСТАВЛЕНА намеренно: она не двигает геометрию, отклик на курсор
// сохраняется. Запрещён только сдвиг — клиент просил рамку «намертво зафиксировать».
//
// ⚠️ Тест читает ИСХОДНИК CSS (прецедент — `ExitButton.test.js`): jsdom в проекте нет.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const css = readFileSync(
  fileURLToPath(new URL('../src/css/stand.css', import.meta.url)),
  'utf8'
).replace(/\/\*[\s\S]*?\*\//g, ''); // комментарии вырезаем: в них это упоминается намеренно

test('белая рамка не двигается под курсором: у .canvas-wrap:hover нет transform', () => {
  const блок = css.slice(css.indexOf('.canvas-wrap:hover'));
  const тело = блок.slice(блок.indexOf('{'), блок.indexOf('}') + 1);

  assert.ok(тело.length > 2, 'блок .canvas-wrap:hover не найден — тест перестал что-либо стеречь');
  assert.ok(!/transform\s*:/.test(тело),
    'у .canvas-wrap:hover снова есть transform — рамка опять поднимается под мышью и колесом');
});
