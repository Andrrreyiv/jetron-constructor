// Сторож против дефекта, который клиент ловил ДВАЖДЫ: перерисовка `innerHTML` сбрасывает
// `scrollLeft` ленты, и она уезжает к первому элементу.
//   31.08 (10:53) — карусель моделей: «нажимаете на самую правую — бегунок обратно в левое
//                   перекидывается… чтобы форма осталась на месте».
//   01.09        — палитра цветов: «у цветов сделать так же как у формы, не перекидывать
//                   курсор на первый цвет».
// Починка в обоих случаях одна: обработчик переставляет класс `.active` руками и НЕ зовёт
// `buildColorPicker()`, который перерисовывает палитру целиком.
//
// ⚠️ Тест читает ИСХОДНИК, а не работает через DOM: jsdom в проекте нет, а поднимать его ради
// одной проверки дороже, чем сама проверка. Он ловит ровно тот способ сломать поведение,
// которым его уже ломали — возврат вызова `buildColorPicker()` внутрь обработчика.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const src = readFileSync(
  fileURLToPath(new URL('../src/js/ui/app.browser.js', import.meta.url)),
  'utf8'
);

// Комментарии вырезаем: в них `buildColorPicker()` упоминается намеренно («звать НЕЛЬЗЯ»).
const код = src.replace(/^\s*\/\/.*$/gm, '');

function телоОбработчика(маркер) {
  const от = код.indexOf(маркер);
  assert.notEqual(от, -1, `не найден обработчик: ${маркер}`);
  const до = код.indexOf('\n    });', от);
  assert.notEqual(до, -1, `не найден конец обработчика: ${маркер}`);
  return код.slice(от, до);
}

test('клик по цвету не перерисовывает палитру целиком', () => {
  const тело = телоОбработчика(`palHost.querySelectorAll('.pcolor')`);
  assert.ok(
    !/\bthis\.buildColorPicker\(/.test(тело),
    'обработчик цвета снова зовёт buildColorPicker() — палитра перерисуется и прокрутка сбросится в 0'
  );
  assert.ok(
    /classList\.add\('active'\)/.test(тело),
    'выбранный цвет должен подсвечиваться перестановкой класса, раз перерисовки больше нет'
  );
  assert.ok(
    /this\._buildModelCarousel\(\)/.test(тело),
    'карусель моделей обязана перестроиться: у другого цвета состав моделей другой'
  );
});

// Тот же сторож для карусели моделей: починка 31.08 своего теста не получила, а дефект
// уже возвращался бы, если бы кто-нибудь «упростил» обработчик обратно до перерисовки.
test('клик по модели не перерисовывает ни палитру, ни карусель', () => {
  const тело = телоОбработчика(`modHost.querySelectorAll('.model-card')`);
  assert.ok(
    !/\bthis\.buildColorPicker\(/.test(тело),
    'обработчик модели снова зовёт buildColorPicker() — вернулся дефект от 31.08'
  );
  assert.ok(
    !/this\._buildModelCarousel\(\)/.test(тело),
    'перестраивать карусель при смене модели нельзя: состав тот же, а прокрутка сбросится'
  );
  assert.ok(
    /classList\.add\('active'\)/.test(тело),
    'выбранная модель подсвечивается перестановкой класса'
  );
});
