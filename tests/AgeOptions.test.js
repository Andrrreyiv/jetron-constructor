// Какие размерные категории вообще предлагать покупателю.
//
// Клиент 09.09: «90% покупателей берут детскую форму, зачем им сразу показывать завышенную
// цену? Если он нажал на чемпион, зачем показывать взрослую цену, если её у нас в природе нет.
// Просто человек проделает работу по созданию макета, а потом окажется, что взрослого размера
// нет, и он спросит, зачем так сделано».

import test from 'node:test';
import assert from 'node:assert/strict';

import { indexCatalogPrices } from '../src/js/core/CatalogPrices.js';
import { ageOptions, normalizeAge, ВОЗРАСТ_ПО_УМОЛЧАНИЮ, ВОЗРАСТЫ } from '../src/js/core/AgeOptions.js';

// Срез живого каталога 09.09: у Чемпиона все позиции детские, у Фаворита взрослых две из пяти.
const позиции = [
  { model: 'Champion', color: 'Белый', age: 'child', price: 1090 },
  { model: 'Фаворит', color: 'Белый', age: 'child', price: 1480 },
  { model: 'Фаворит', color: 'Сиреневый', age: 'child', price: 1480 },
  { model: 'Фаворит', color: 'Сиреневый', age: 'adult', price: 1680 },
];

test('у Чемпиона взрослой формы нет в природе — взрослую категорию не предлагаем', () => {
  const idx = indexCatalogPrices(позиции);
  assert.deepEqual(ageOptions(idx, { line: 'Champion', color: 'Белый' }), ['child']);
});

test('обе категории заведены — предлагаем обе, детская первой как на экране', () => {
  const idx = indexCatalogPrices(позиции);
  assert.deepEqual(ageOptions(idx, { line: 'Фаворит', color: 'Сиреневый' }), ['child', 'adult']);
});

// Голосовое 08:42: «детскую передвигаем влево, взрослую вправо».
test('детская стоит слева', () => {
  assert.deepEqual(ВОЗРАСТЫ, ['child', 'adult']);
  const idx = indexCatalogPrices(позиции);
  assert.equal(ageOptions(idx, { line: 'Фаворит', color: 'Белый' })[0], 'child');
});

// Голосовое клиента 09.09: «ну тогда и ставим запасные взрослые 1680, детские 1480, как бы
// здесь без вариантов, это все игровые формы, и мы цены приравниваем к фактическим».
// У белого Фаворита взрослой позиции в каталоге нет, но взрослый Фаворит как товар СУЩЕСТВУЕТ
// (заведён на сиреневом) — значит категорию прячем не по расцветке, а по ЛИНЕЙКЕ. Разница
// принципиальная: взрослого Чемпиона нет нигде, а взрослый Фаворит просто не доведён.
test('расцветка без взрослой позиции, но линейка взрослая есть — категорию оставляем', () => {
  const idx = indexCatalogPrices(позиции);
  assert.deepEqual(ageOptions(idx, { line: 'Фаворит', color: 'Белый' }), ['child', 'adult']);
});

test('без каталога предлагаем обе: демо-стенд не должен остаться без выбора', () => {
  assert.deepEqual(ageOptions(null, { line: 'Champion', color: 'Белый' }), ['child', 'adult']);
  assert.deepEqual(ageOptions(indexCatalogPrices([]), { line: 'Champion', color: 'Белый' }), ['child', 'adult']);
});

test('расцветки нет в каталоге вовсе — предлагаем обе, а не пустоту', () => {
  // Коралловая форма или новая расцветка, которую ещё не завели товаром: запереть покупателя
  // без единой кнопки хуже, чем показать обе с запасной ценой из конфига, как было всегда.
  const idx = indexCatalogPrices(позиции);
  assert.deepEqual(ageOptions(idx, { line: 'Волна', color: 'Коралловый' }), ['child', 'adult']);
});

test('по умолчанию детская: клиент 09.09 — «90% покупателей берут детскую форму»', () => {
  // Раньше конструктор открывался на взрослой и на Чемпионе сразу показывал 1280 ₽ за товар,
  // которого в магазине не существует.
  assert.equal(ВОЗРАСТ_ПО_УМОЛЧАНИЮ, 'child');
});

test('выбранного возраста нет у новой расцветки — молча переносим на доступный', () => {
  // Человек выбрал взрослую на Легенде, потом переключился на Чемпиона: оставить выбор
  // нельзя (взрослого Чемпиона нет), а показать пустой сегмент тем более.
  assert.equal(normalizeAge('adult', ['child']), 'child');
  assert.equal(normalizeAge('child', ['adult', 'child']), 'child');
  assert.equal(normalizeAge('adult', ['adult', 'child']), 'adult');
});

test('пустой список возрастов не роняет выбор', () => {
  assert.equal(normalizeAge('adult', []), 'adult');
  assert.equal(normalizeAge('', ['adult', 'child']), 'adult');
});
