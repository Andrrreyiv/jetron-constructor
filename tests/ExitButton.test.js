// Сторож против ВОЗВРАТА крестика выхода из конструктора.
//
// История у кнопки двойная, и без неё этот тест выглядит как каприз:
//   17.07.2026 клиент: «из самого конструктора нет выхода, добавьте крестик» — кнопку завели,
//              она уводила на `/shop/` (`_exitConstructor`).
//   02.09.2026 клиент (голосовое 08:27): «я ещё, честно говоря, не знаю, нужен ли этот крестик…
//              если человек нажмёт — конструктор закроется? А дальше что?.. там же будет
//              в телефоне сверху шапка, это менюшка, а в компьютере тоже менюшка. Наверно,
//              крестик надо убрать, и всё, наверное, там станет на свои места, потому что
//              сейчас кнопки вообще вышли за рамки».
//
// Убирать было безопасно, и это проверено, а не предположено: на боевом конструктор живёт
// как `<iframe src="/constructor/">` на странице WP 3443 (`docs/ДЕПЛОЙ-боевой.md`), то есть
// вокруг него всегда есть обычная страница сайта с шапкой и меню. Покупатель не запирается.
//
// ⚠️ Возвращать кнопку без нового слова клиента нельзя: она делила правый верхний угол
// с пилюлей «в карточку» и торчала на 8 px правее ряда (замер 02.09) — это и есть
// «кнопки вышли за рамки».
//
// ⚠️ Тест читает ИСХОДНИК, а не работает через DOM: jsdom в проекте нет (см. PickerRedraw.test.js).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const js = readFileSync(
  fileURLToPath(new URL('../src/js/ui/app.browser.js', import.meta.url)),
  'utf8'
);
const css = readFileSync(
  fileURLToPath(new URL('../src/css/stand.css', import.meta.url)),
  'utf8'
);

// Комментарии вырезаем: в них имя `constructor-exit` упоминается намеренно, как надгробие.
const кодJs = js.replace(/^\s*\/\/.*$/gm, '');
const кодCss = css.replace(/\/\*[\s\S]*?\*\//g, '');

test('крестика выхода из конструктора нет ни в JS, ни в CSS', () => {
  assert.ok(
    !/constructor-exit/.test(кодJs),
    'в app.browser.js вернулся узел `.constructor-exit` — клиент 02.09 просил его убрать'
  );
  assert.ok(
    !/_installExitButton|_exitConstructor/.test(кодJs),
    'вернулись методы установки/срабатывания крестика — вместе с ними вернётся и сама кнопка'
  );
  assert.ok(
    !/\.constructor-exit/.test(кодCss),
    'в stand.css вернулись правила `.constructor-exit` — правила без узла это мёртвый код'
  );
});
