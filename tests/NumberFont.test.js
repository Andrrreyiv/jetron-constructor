// Раздельный шрифт фамилии и номера: как это подключено в браузерном слое.
//
// Клиент 25.09 (расшифровка `docs/voice-client-2026-09-25.txt`): покупатели обходом ставят
// номер клубным шрифтом при русской фамилии шрифтом РПЛ. Решено без новых кнопок («визуально
// ничего не должно поменяться»): у номера свой шрифт `numberFontId`.
// ☠️ Голосовое 15:21 отменило утреннюю привязку к курсору: «нам надо не привязывать курсор,
// а привязывать латиницу». Клик по шрифту: с кириллицей — меняет фамилию и номер; только
// латиница при русской фамилии — меняет только номер. Правило — `core/TextColor.js`
// (`шрифтПоКлику`, `латиницаЗакрытаНаСпине`), здесь проверяется проводка.
//
// ⚠️ Тест читает ИСХОДНИК: jsdom в проекте нет. Проверки ловят ровно те способы сломать
// поведение, которые видны заранее: общий шрифт у номера, возврат привязки к курсору
// и шрифт номера, не попавший в ленивую загрузку (класс дефекта 15.09).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const код = readFileSync(new URL('../src/js/ui/app.browser.js', import.meta.url), 'utf8');

const метод = (имя) => {
  const m = код.match(new RegExp(`\\n  ${имя}\\([^)]*\\)\\s*\\{([\\s\\S]*?)\\n  \\}`));
  assert.ok(m, `метод ${имя}() должен существовать`);
  return m[1];
};

test('номер на спине рисуется своим шрифтом, фамилия — своим', () => {
  const ветка = код.match(/if \(opt\.kind === 'name_number'\) \{([\s\S]*?)\n    \} else if \(opt\.kind === 'upload'\)/);
  assert.ok(ветка, 'ветка name_number должна существовать в applyOption()');
  assert.match(ветка[1], /шрифтНомера\(c, fontId\)/, 'номер берёт свой шрифт, а по умолчанию — шрифт фамилии');
  assert.match(ветка[1], /draw\(opt\.nameZone, \{ type: 'text', value: c\.name, fontId,/,
    'фамилия рисуется шрифтом фамилии');
  assert.match(ветка[1], /draw\(opt\.numberZone, \{ type: 'text', value: c\.number, fontId: номерШрифт,/,
    'номер рисуется шрифтом номера, а не общим');
});

// Голосовое 13:35: «шрифт на груди логотипа и под номером, он привязан к фамилии».
test('текстовые логотипы ведутся от шрифта фамилии', () => {
  const t = метод('_ведомыеОтСпины');
  assert.match(t, /linkedLetterFont\(/, 'надписи-логотипы — буквы, их ведёт шрифт фамилии');
  assert.doesNotMatch(t, /linkedNumberFont\(/, 'шрифт номера бывает латинским клубным и русских букв не держит');
});

test('клик по шрифту в «Фамилии и номере» решается по латинице, а не по курсору', () => {
  const клик = код.match(/body\.querySelectorAll\('\.font-opt'\)\.forEach\(\(b\) => \{([\s\S]*?)\n    \}\);/);
  assert.ok(клик, 'обработчик клика по шрифту должен существовать');
  assert.match(клик[1], /шрифтПоКлику\(/, 'правило клика живёт в core/TextColor.js');
  assert.match(клик[1], /opt\.kind === 'name_number'/, 'остальные опции пишут шрифт как раньше');
});

// Голосовое 15:21: «никто не догадается переставить курсор на фамилию… тётушка 50-летняя
// в жизни не догадается». Любая привязка к фокусу поля — возврат отменённого правила.
test('привязки к курсору нет', () => {
  assert.doesNotMatch(код, /_последнееПоле|_запомнитьПоле|_цельШрифта/,
    'правило «шрифт идёт в поле, где был курсор» отменено клиентом 25.09 в 15:21');
  const поля = код.match(/body\.querySelectorAll\('input\[type="text"\]'\)\.forEach\(\(inp\) => \{([\s\S]*?)\n    \}\);/);
  assert.ok(поля, 'проводка текстовых полей должна существовать');
  assert.doesNotMatch(поля[1], /inp\.onfocus/, 'шрифт не зависит от того, в каком поле стоит курсор');
});

test('замки латиницы у «Фамилии и номера» считаются одним правилом', () => {
  assert.match(метод('_латиницаЗакрыта'), /латиницаЗакрытаНаСпине\(/);
  // Карточка и пересчёт на лету обязаны считать одинаково, иначе разъедутся.
  assert.match(метод('updateFontLocks'), /this\._латиницаЗакрыта\(/);
  const карточка = код.match(/\n  fontColorHtml\(c[^)]*\)\s*\{([\s\S]*?)\n    return `/);
  assert.ok(карточка, 'fontColorHtml() должен существовать');
  assert.match(карточка[1], /this\._латиницаЗакрыта\(/);
});

// ☠️ Класс дефекта 15.09: шрифт, которого нет в ленивой загрузке, уходит в PNG заказа
// системным sans, а спецификация честно пишет его название.
test('шрифт номера попадает в загрузку шрифтов черновика', () => {
  const t = код.match(/\n  _шрифтыЧерновика\(\)\s*\{([\s\S]*?)\n  \}/);
  assert.ok(t, '_шрифтыЧерновика() должен существовать');
  assert.match(t[1], /c\.numberFontId/, 'иначе восстановленный номер нарисуется чужим шрифтом');
});
