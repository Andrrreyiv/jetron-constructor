// Защита полей ввода покупателя (фамилия, номер, текст на груди и спине).
//
// Клиент 24.09, голосовое 11:50: «мы же там вводим фамилию, номер, это же поля ввода —
// вы как-то их защищали? У нас есть кто сайт создавал, они там в этом плане очень чётко
// делали по полям ввода… если нет, то я передам ребятам». Ответ — «защищали», и эти
// сторожа существуют, чтобы он не перестал быть правдой после очередной правки вёрстки.
//
// Защита двухслойная, и слои НЕ взаимозаменяемы:
//   1) браузер — экранирование при выводе (escapeHtml) и потолки длины (maxlength);
//   2) сервер — sanitize_* на входе, esc_html/esc_url на выводе, потолок спецификации.
// Браузеру верить нельзя: поле правится через инструменты разработчика, а запрос
// отправляется и вовсе мимо страницы. Поэтому здешние потолки — про опрятность заказа,
// а настоящая граница стоит в PHP (jetron-constructor.php, jetron-orders.php).
//
// ⚠️ Тесты читают ИСХОДНИК: jsdom в проекте нет, а и экранирование, и атрибуты полей
// живут в строках разметки. Живой замер 24.09 (локальный стенд, Chrome): в «Фамилию»
// введено `<img src=x onerror=...>`, в «Номер» — `"><script>…</script>`; после полной
// перерисовки в панели 0 тегов img и script, обработчик не сработал, окно заказа показало
// payload текстом. Повторять замер — тем же способом, а не глазами по коду.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const код = readFileSync(new URL('../src/js/ui/app.browser.js', import.meta.url), 'utf8');
const php = readFileSync(new URL('../deploy/jetron-constructor.php', import.meta.url), 'utf8');

// Любое значение покупателя попадает в разметку через шаблонную строку. Потеряется
// escapeHtml у одного поля — и текст из поля станет разметкой ровно в этом месте.
test('значения полей уходят в разметку только через escapeHtml', () => {
  assert.match(код, /const escapeHtml = \(s\) => String\(s\)\.replace\(\/\[&<>"'\]\/g/,
    'escapeHtml обязан гасить и кавычки: значение подставляется внутрь атрибута value');
  const поля = код.match(/<input class="opt-in[^>]*>/g) || [];
  assert.ok(поля.length >= 4, 'полей ввода должно быть найдено хотя бы четыре');
  for (const поле of поля) {
    const value = поле.match(/value="([^"]*)"/);
    assert.ok(value, `у поля должно быть value: ${поле}`);
    assert.match(value[1], /^\$\{escapeHtml\(/,
      `значение обязано экранироваться, иначе XSS из поля: ${поле}`);
  }
});

// Игровой номер длиннее трёх цифр не бывает, а потолка у поля не было вовсе: «12345»
// печаталось на спине как есть. Три знака обрезал только образец в превью шрифта
// (fontSampleText), то есть на самом макете строка оставалась целиком.
test('номер ограничен тремя знаками', () => {
  const номера = (код.match(/<input class="opt-in[^>]*data-field="number"[^>]*>/g) || []);
  assert.ok(номера.length >= 2, 'полей номера два: в «Фамилия и номер» и отдельное');
  for (const поле of номера) {
    assert.match(поле, /maxlength="3"/, `поле номера без потолка: ${поле}`);
  }
});

test('фамилия и свободный текст имеют потолок длины', () => {
  const фамилия = код.match(/<input class="opt-in[^>]*data-field="name"[^>]*>/);
  assert.ok(фамилия, 'поле фамилии должно существовать');
  assert.match(фамилия[0], /maxlength="24"/, 'самая длинная двойная фамилия короче');
  const текст = код.match(/<input class="opt-in[^>]*data-field="text"[^>]*>/);
  assert.ok(текст, 'поле свободного текста должно существовать');
  assert.match(текст[0], /maxlength="40"/, 'названия клуба и спонсора в 40 знаков помещаются');
});

// Главное: сервер не должен верить браузеру. Потолок в поле обходится за секунду,
// поэтому спецификация режется ещё раз при приёме в корзину.
test('спецификация режется по длине на сервере, а не только в поле', () => {
  assert.match(php, /sanitize_textarea_field\(wp_unslash\(\$_POST\['jetron_spec'\]\)\)/,
    'текст спецификации обязан проходить sanitize_textarea_field');
  assert.match(php, /mb_substr\(\$spec, 0, 4000\) : substr\(\$spec, 0, 4000\)/,
    'без потолка подставленный мегабайт лёг бы в мету заказа целиком');
});

// Логотип приезжает как data-URL, то есть строкой из браузера. Заголовок в ней пишет кто
// угодно, поэтому содержимое проверяется отдельно от заголовка.
test('в медиатеку не попадает то, что не является картинкой', () => {
  assert.match(php, /function jetron_looks_like_image\(\$bytes, \$ext\)/,
    'проверка содержимого файла обязана существовать');
  const вызовы = php.match(/jetron_looks_like_image\(\$bytes, \$ext\)/g) || [];
  assert.ok(вызовы.length >= 3,
    'проверка нужна обоим приёмникам: и макету заказа, и логотипу покупателя');
  assert.match(php, /getimagesizefromstring/, 'смотрим сами байты, а не заголовок data:');
});
