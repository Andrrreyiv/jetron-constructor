// Размер выбирается ПЕРВЫМ, до сборки макета.
//
// Клиент 09.09 (голосовое 2): «в самом верху, где у нас написано „выберите“ — не надо это.
// Просто переносим вот эти кнопки из комплектации, детская и взрослая, в самый верх… по
// умолчанию стоит детская… а внизу кнопка таблица размеров, человек её открывает, видит,
// какие есть размеры, сразу выбирает размер, а дальше уже пошёл по конструктору рисовать.
// Потому что, допустим, какой-то формы не будет, какого-то размера, чтобы он лишнее время
// своё не тратил на заполнение этого конструктора».
//
// И раньше того, письмом: «у нас в конструкторе две таблицы размеров, в комплектации и в
// заказе. В комплектации нельзя выбрать размер, а в заказе можно» — значит таблица должна
// быть ОДНА и та же, выбирающая, а не две разных.
//
// Вёрстку тесты в этом проекте не стерегут (см. CLAUDE.md), поэтому здесь сторожим не пиксели,
// а порядок и связи в самом исходнике: что блок выбора стоит выше конструктора опций, что
// таблица размеров одна на два места и что размерная категория больше не спрятана в
// «Комплектации». Пиксели по-прежнему смотрим глазами на пяти профилях.

import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';

const код = fs.readFileSync(new URL('../src/js/ui/app.browser.js', import.meta.url), 'utf8');
const тело = (имя) => {
  const m = код.match(new RegExp(`\\n  ${имя}\\(\\)\\s*\\{([\\s\\S]*?)\\n  \\}`));
  assert.ok(m, `метод ${имя}() должен существовать`);
  return m[1];
};

test('выбор размера стоит выше конструктора опций', () => {
  const панель = тело('buildPanel');
  const размер = панель.indexOf('id="size-first"');
  const опции = панель.indexOf('id="opt-list"');
  assert.ok(размер !== -1, 'в панели должен быть блок выбора размера');
  assert.ok(размер < опции, 'размер выбирается ДО того, как человек начнёт рисовать');
});

test('надписи над блоком нет, вместо неё сразу выбор', () => {
  // «В самом верху, где у нас написано „выберите“ — не надо это». Единственный заголовок
  // панели на боевом 09.09 — «Соберите форму», замер телефона 375 показал его первым текстом.
  assert.doesNotMatch(тело('buildPanel'), /Соберите форму/);
});

test('размерная категория и таблица размеров переехали из «Комплектации» наверх', () => {
  const панель = тело('buildPanel');
  const комплектация = панель.indexOf('id="opt-extra"');
  assert.ok(комплектация !== -1);
  assert.doesNotMatch(панель.slice(комплектация), /Размерная категория|id="age-seg"|id="size-btn"/,
    'внутри «Комплектации» ни сегмента возраста, ни кнопки таблицы больше нет');
  const бар = тело('renderSizeBar');
  assert.match(бар, /id="age-seg"/, 'сегмент возраста рисуется в верхнем блоке');
  assert.match(бар, /id="size-btn"/, 'кнопка таблицы размеров — там же');
  assert.match(бар, /this\.renderAgeSeg\(\)/);
  assert.match(бар, /this\.size/, 'выбранный размер виден прямо в баре, а не только в заказе');
});

test('на кнопках возраста цены нет — цена на экране одна, внизу', () => {
  // Клиент 09.09 по своему скриншоту формы New: «цена внизу итого стоит правильно, 780,
  // а взрослая-детская стоит 1090 и 1280… предлагаю взрослая-детская цены там убрать,
  // пускай внизу она стоит и всё… просто надпись взрослая и детская, покрупнее сделаем».
  // Расхождение было настоящим: подписи брались из запасного прайса конфига, «Итого» —
  // из каталога.
  const сегмент = тело('renderAgeSeg');
  assert.doesNotMatch(сегмент, /money\(/, 'в подписи кнопки цены быть не должно');
  assert.match(сегмент, /\$\{ПОДПИСЬ\[age\]\}<\/button>/, 'в кнопке остаётся одна подпись');
});

test('таблица размеров одна на оба места и в обоих даёт выбрать размер', () => {
  // Жалоба клиента 09.09: «в комплектации нельзя выбрать размер, а в заказе можно».
  assert.match(тело('showSizes'), /this\.sizeTableHtml\(/);
  const заказ = код.match(/\n  showOrder\(\)\s*\{([\s\S]*?)\n  \}/);
  assert.ok(заказ);
  assert.match(заказ[1], /this\.sizeTableHtml\(/);
  const таблица = код.match(/\n  sizeTableHtml\(cat\)\s*\{([\s\S]*?)\n  \}/);
  assert.ok(таблица, 'метод sizeTableHtml(cat) должен существовать');
  assert.match(таблица[1], /size-row/, 'строки таблицы кликабельны');
});

test('выбор размера в таблице сохраняется и виден сразу', () => {
  const метод = тело('showSizes');
  assert.match(метод, /this\.size = /, 'клик по строке запоминает размер');
  assert.match(метод, /renderSizeBar\(\)/, 'верхний бар обновляется тут же');
});
