// Цвет надписей: кто у кого его берёт.
//
// Клиент 30.08 (скриншоты + текст): «привяжи пожалуйста цвет номера на груди к цвету надписей
// на спине, чтобы они одинакового цвета были». На его снимке фамилия и номер на спине белые,
// а номер на груди чёрный — потому что у номера на груди своего выбора цвета нет и никогда
// не было: он рисовался цветом по умолчанию (`this.textColor`) мимо выбора клиента.

import test from 'node:test';
import assert from 'node:assert/strict';

import { linkedNumberColor, linkedNumberFont, ведомыеПерерисовать, яркостьТкани, знакБелый } from '../src/js/core/TextColor.js';

// Опции размещения из `mock-config.json`: спина — `name_number`, грудь — `chest_number`.
const опции = [
  { id: 'name_number', kind: 'name_number' },
  { id: 'chest_number', kind: 'number' }
];

test('номер на груди берёт цвет у надписей на спине, а не цвет по умолчанию', () => {
  const кэш = { name_number: { name: 'ИВАН', number: '10', color: '#ffffff' } };
  assert.equal(linkedNumberColor(опции, кэш, '#111111'), '#ffffff');
});

// Клиент 31.08 письменно: «Шрифт номера на груди, привязать к шрифту на спине».
// Тот же дефект, что был с цветом: своего выбора шрифта у номера на груди нет,
// он рисовался шрифтом по умолчанию мимо выбора клиента на спине.
test('номер на груди берёт шрифт у надписей на спине, а не шрифт по умолчанию', () => {
  const кэш = { name_number: { name: 'ИВАН', number: '10', fontId: 'college' } };
  assert.equal(linkedNumberFont(опции, кэш, 'default'), 'college');
});

// Замер 01.09 в браузере: сама привязка работала, а на экране её было НЕ ВИДНО. Смена шрифта
// на спине перерисовывала спину и номер на шортах, а уже нарисованный номер на груди оставался
// прежним шрифтом (`rpl` при `stalinist` на спине) — до следующего ввода в его поле.
// Причина: перерисовку ведомых включал только патч с ЦВЕТОМ (правка 30.08), про шрифт (31.08)
// то же условие не расширили. Для клиента это неотличимо от «привязку не сделали».
test('смена шрифта на спине, как и цвета, обязана перерисовать ведомые номера', () => {
  assert.equal(ведомыеПерерисовать({ color: '#ffffff' }), true);
  assert.equal(ведомыеПерерисовать({ fontId: 'stalinist' }), true);
  // Ввод самой фамилии ведомых не трогает: их значения от неё не зависят.
  assert.equal(ведомыеПерерисовать({ name: 'ИВАНОВ' }), false);
});

// Клиент 04.09: «обратите внимание, логотип на груди чёрный, предвижу необходимость настройки
// цвета логотипа на груди». Правило выбора цвета у знака есть с самого начала — тёмная ткань
// значит белый знак — но яркость ткани считалась СРЕДНИМ по всей выборке, и это врало дважды.
// Оба случая ниже — замеренные, а не выдуманные.
const пиксели = (...пачки) => {
  const d = [];
  for (const [n, r, g, b] of пачки) for (let i = 0; i < n; i++) d.push(r, g, b, 255);
  return d;
};

test('яркость ткани не считает белый лист мокапа и не усредняет двухцветную ткань', () => {
  // 1. Красный Winner, грудь. Бокс знака свисает с формы на белый лист мокапа: 36 % выборки —
  // чистый белый фон. Среднее давало 156.5 при пороге 128 → ЧЁРНЫЙ знак на красной футболке.
  // Сама ткань — 102.
  const красный = пиксели([36, 255, 255, 255], [64, 206, 60, 45]);
  assert.ok(Math.abs(яркостьТкани(красный) - 102) < 3,
    `ожидалась яркость ткани ~102, получено ${яркостьТкани(красный)}`);

  // 2. champion-white. Знак стоит ровно на границе бордового и белого, среднее выходило 128.8
  // при пороге 128 — то есть цвет знака решался подбрасыванием монетки. Медиана берёт то,
  // чего под знаком БОЛЬШЕ: белого.
  const чемпион = пиксели([55, 200, 200, 200], [45, 60, 20, 25]);
  assert.ok(яркостьТкани(чемпион) > 150,
    `на преимущественно белой ткани ожидалась яркость > 150, получено ${яркостьТкани(чемпион)}`);

  // 3. Знак почти целиком мимо формы (Оранжевый, шорты): ткани в выборке меньше четверти.
  // Отбрасывать фон тут нельзя — по трём пикселям цвет не решают. Это дефект ПОЗИЦИИ знака,
  // и он обязан выглядеть как «фон», а не притворяться тканью.
  const мимо = пиксели([95, 255, 255, 255], [5, 40, 40, 40]);
  assert.ok(яркостьТкани(мимо) > 200,
    `при нехватке ткани ожидался откат на всю выборку, получено ${яркостьТкани(мимо)}`);
});

// Само решение «какой файл знака брать». Держим его отдельно от замера, потому что клиент
// 04.09 просит «настройку цвета логотипа»: ручной выбор придёт сюда, а не в статистику.
test('белый знак берут только на тёмной ткани; при неизвестной яркости — чёрный, как раньше', () => {
  assert.equal(знакБелый(102), true);   // красный Winner, грудь
  assert.equal(знакБелый(198), false);  // champion-white
  // Ткань неизвестна (нет подложки, картинка не загрузилась) — поведение прежнее, не белый.
  assert.equal(знакБелый(null), false);
});
