# -*- coding: utf-8 -*-
"""Сторож на стыке кода и картинок: FRAME_ASPECT обязан совпадать с реальными мокапами.

Клиент 02.09 (волна 5): «чтобы на всех картинках вот эта белая рамка была без движения,
намертво зафиксирована, и чтобы она была одна, чтобы она не гуляла вверх-вниз». Рамка
одна потому, что `CanvasFit.js` держит её пропорцию КОНСТАНТОЙ. Взята пропорция самого
низкого кадра — Champion 836/900: клиент назвал его размеры идеальными, и только эта
константа никого не уменьшает (любая выше — режет ширину всем линейкам сразу).

⚠️ Опасность, ради которой написан файл: константа живёт в JS, а её значение приходит
из WebP на диске. Пересборка мокапов (`run_normalize.py`, новый исходник `Star чёрный`,
смена `TOP_PX`) меняет высоты кадров молча — за 02.09 они уже съезжали 992..1110 -> 836..954,
а 03.09 композит `Star чёрный` от клиента двинул их ВТОРОЙ раз: 836..954 -> 836..937
(Star 954 -> 878, самой высокой стала New). Опасность не теоретическая, она срабатывала дважды.
Если Champion станет ниже, а константа останется, картинка вылезет за рамку и вернётся
вертикальный перелив, который вылечила волна 4. Тесты вёрстку не стерегут, поэтому
единственная страховка — сверка числа в коде с числом на диске.
"""
import re
from pathlib import Path

import pytest
from PIL import Image

КОРЕНЬ = Path(__file__).resolve().parent.parent
МОКАПЫ = КОРЕНЬ / "assets" / "mockups"
CANVAS_FIT = КОРЕНЬ / "src" / "js" / "core" / "CanvasFit.js"


def _константа_из_js():
    """FRAME_ASPECT = 836 / 900 -> (836, 900). Разбираем дробь, а не готовое число:
    в коде она записана дробью намеренно, чтобы читались исходные пиксели кадра."""
    исходник = CANVAS_FIT.read_text(encoding="utf-8")
    m = re.search(r"export const FRAME_ASPECT\s*=\s*(\d+)\s*/\s*(\d+)\s*;", исходник)
    assert m, "FRAME_ASPECT пропал или записан не дробью — сверить с мокапами руками"
    return int(m.group(1)), int(m.group(2))


def _кадры():
    файлы = sorted(МОКАПЫ.glob("*.webp"))
    if not файлы:
        pytest.skip("мокапы не собраны")
    return {p.name: Image.open(p).size for p in файлы}


def test_frame_aspect_равен_самому_низкому_кадру_на_диске():
    высота, ширина = _константа_из_js()
    размеры = _кадры()
    ширины = {w for w, _ in размеры.values()}
    assert ширины == {ширина}, f"ширина кадров разошлась с константой: {sorted(ширины)}"
    самый_низкий = min(h for _, h in размеры.values())
    assert высота == самый_низкий, (
        f"FRAME_ASPECT = {высота}/{ширина}, а самый низкий кадр на диске {самый_низкий}. "
        "Мокапы пересобраны — обновить константу в CanvasFit.js и перемерить рамку глазами."
    )


def test_ни_один_кадр_не_ниже_рамки():
    """Тот же факт, но по КАЖДОМУ файлу: так ошибка называет конкретную расцветку,
    а не одно число. Кадр ниже рамки не поместился бы в неё по высоте — картинка
    вылезла бы за белое поле, и вернулся бы вертикальный перелив."""
    высота, ширина = _константа_из_js()
    for имя, (w, h) in _кадры().items():
        assert h >= высота, f"{имя}: кадр {w}x{h} ниже рамки {ширина}x{высота}"
