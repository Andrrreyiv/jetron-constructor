// Поле загрузки логотипа обязано пускать webp.
//
// Клиент 13.09 прислал снимок выборщика файлов: его логотип «СШОР Олимп» лежит в четырёх видах,
// и `.webp` показан СЕРЫМ — выбрать нельзя. Запрета в коде не было: `prepareImage()` на MIME
// не смотрит вообще, файл до 1,5 МБ читается через `readAsDataURL` как есть, тяжёлый идёт через
// <img> + canvas, а webp браузеры декодируют. Резал один `accept="image/*"`: мобильные
// выборщики раскрывают групповую маску в собственный список типов, и webp в него попадает
// не всегда. Лечение — перечислить расширения рядом с маской.
//
// ⚠️ Тест читает ИСХОДНИК: jsdom в проекте нет, а поведение выборщика всё равно живёт
// в атрибуте разметки, а не в логике.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const код = readFileSync(new URL('../src/js/ui/app.browser.js', import.meta.url), 'utf8');

test('в загрузку логотипа пускают webp, а не только групповую маску', () => {
  const строка = код.match(/const UPLOAD_ACCEPT = '([^']+)'/);
  assert.ok(строка, 'константа UPLOAD_ACCEPT должна быть определена');
  const accept = строка[1];
  assert.match(accept, /\.webp/, 'ровно этот формат клиент и не смог выбрать');
  assert.match(accept, /image\/\*/, 'групповую маску не теряем: на десктопе она удобнее');
  for (const расширение of ['.png', '.jpg', '.jpeg']) {
    assert.ok(accept.includes(расширение), `${расширение} обязан остаться доступным`);
  }
});

test('поле файла берёт список из константы, а не из своей строки', () => {
  assert.match(код, /<input type="file" accept="\$\{UPLOAD_ACCEPT\}"/,
    'иначе список разъедется с константой и тест перестанет что-либо стеречь');
  // Смотрим САМИ теги, а не весь файл: в комментарии рядом с константой прежняя маска
  // процитирована намеренно, и проверка по всему тексту падала бы на объяснении.
  const поля = код.match(/<input type="file"[^>]*>/g) || [];
  assert.ok(поля.length, 'поле загрузки файла должно существовать');
  for (const поле of поля) {
    assert.doesNotMatch(поле, /accept="image\/\*"/,
      'голая маска image/* — ровно то, на чём webp и отваливался');
  }
});

// Страховка на будущее: формат в списке бессмысленен, если prepareImage его не примет.
// Явных проверок MIME там быть не должно — иначе появится второе место, где формат
// запрещается, и списки разъедутся.
test('prepareImage не заводит собственный запрет по формату', () => {
  const метод = код.match(/\n  prepareImage\(file\)\s*\{([\s\S]*?)\n  \}/);
  assert.ok(метод, 'метод prepareImage() должен существовать');
  assert.doesNotMatch(метод[1], /file\.type/,
    'проверка типа здесь дала бы второй, невидимый фильтр поверх accept');
});
