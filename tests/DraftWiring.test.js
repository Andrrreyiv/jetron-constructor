// Сторож проводки черновика (п. 7 клиента 07.09): «навставлял логотипов, обновил страницу —
// всё сбросилось… если в моменте за день он обновляет страницу несколько раз, ходит, заходит
// в корзину». Сама логика лежит в чистых `core/DraftStorage.js` и `core/DraftShape.js`
// и проверена своими наборами; здесь проверяется, что конструктор их ЗОВЁТ, и в верном порядке.
//
// ⚠️ Тест читает ИСХОДНИК, а не работает через DOM: jsdom в проекте нет (см. PickerRedraw.test.js).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const src = readFileSync(
  fileURLToPath(new URL('../src/js/ui/app.browser.js', import.meta.url)),
  'utf8'
);
const код = src.replace(/^\s*\/\/.*$/gm, '');

const start = код.match(/async start\(\)\s*\{([\s\S]*?)\n  \}/);

// Панель и палитра рисуются один раз и уже с данными покупателя. Восстанови мы черновик
// ПОСЛЕ них — покупатель увидел бы пустые карточки, а его фамилия появилась бы рывком.
test('черновик восстанавливается до отрисовки панели', () => {
  assert.ok(start, 'метод start() должен существовать');
  const тело = start[1];
  const восстановление = тело.indexOf('_restoreDraft(');
  const панель = тело.indexOf('buildPanel(');
  assert.ok(восстановление !== -1, 'start() обязан звать восстановление черновика');
  assert.ok(восстановление < панель, 'восстановление идёт РАНЬШЕ buildPanel()');
});

// Хранилище и разбор черновика живут в core и проверяются в Node без браузера.
// Своя копия логики в браузерном файле означала бы, что её никто не стережёт.
test('черновик читается и пишется чистыми модулями core, а не своей копией', () => {
  assert.match(код, /import \{[^}]*loadDraft[^}]*\} from '\.\.\/core\/DraftStorage\.js/);
  assert.match(код, /import \{[^}]*sanitizeDraft[^}]*\} from '\.\.\/core\/DraftShape\.js/);
  assert.match(код, /_restoreDraft\(\)\s*\{/, 'метод восстановления должен быть определён');
});

// Точка записи выбрана одна — `updatePrice()`. Её зовут все двенадцать мест, где покупатель
// что-то меняет (возраст, гетры, количество, любая опция, заказ), поэтому отдельные вызовы
// по кнопкам не нужны и не разъедутся: добавили новую кнопку — черновик пишется сам.
test('черновик пишется из updatePrice, до её раннего возврата', () => {
  const цена = код.match(/\n  updatePrice\(\)\s*\{([\s\S]*?)\n  \}/);
  assert.ok(цена, 'метод updatePrice() должен существовать');
  const тело = цена[1];
  const запись = тело.indexOf('_saveDraft(');
  const возврат = тело.indexOf('if (!totalEl) return');
  assert.ok(запись !== -1, 'updatePrice() обязан сохранять черновик');
  assert.ok(возврат === -1 || запись < возврат, 'запись идёт ДО раннего возврата по totalEl');
});

// Мина, из-за которой черновик умер бы молча: `updatePrice()` зовётся ещё и из `renderAll()`,
// то есть ДО того, как прошлый черновик восстановлен. Без флага первая же отрисовка
// записала бы поверх хорошей записи пустой конструктор.
test('запись черновика заперта флагом до конца восстановления', () => {
  const метод = код.match(/\n  _saveDraft\(\)\s*\{([\s\S]*?)\n  \}/);
  assert.ok(метод, 'метод _saveDraft() должен быть определён');
  assert.match(метод[1], /if \(!this\._draftReady\) return/);
  assert.match(метод[1], /saveDraft\(/);
  assert.match(метод[1], /snapshotOf\(this\)/);
});

// Данные опций восстанавливаются в кэш, но на макет их наносит `applyOption()`, а он
// требует уже построенных зон и холстов. Значит вызов идёт ПОСЛЕ renderAll, иначе
// покупатель увидит свою фамилию в карточке и пустую форму на картинке.
test('восстановленные опции наносятся на макет после построения холстов', () => {
  const тело = start[1];
  const холсты = тело.indexOf('renderAll(');
  const нанесение = тело.indexOf('_applyRestoredOptions(');
  assert.ok(нанесение !== -1, 'start() обязан нанести восстановленные опции');
  assert.ok(холсты < нанесение, 'нанесение идёт ПОСЛЕ renderAll()');
  const метод = код.match(/\n  _applyRestoredOptions\(\)\s*\{([\s\S]*?)\n  \}/);
  assert.ok(метод, 'метод _applyRestoredOptions() должен быть определён');
  assert.match(метод[1], /applyOption\(/);
  assert.match(метод[1], /optionActive\(/, 'наносим только опции с данными и включённым тумблером');
});

// Состояние восстановлено в поля объекта и уже посчитано в цене, но покупатель верит ГЛАЗАМ:
// увидев «Взрослая» при восстановленной детской, он нажмёт её ещё раз и обнулит себе выбор.
// Значит сама разметка панели рисуется ИЗ состояния, а не из умолчаний.
test('восстановленные возраст, гетры и количество видны в самой панели', () => {
  const панель = код.match(/\n  buildPanel\(\)\s*\{([\s\S]*?)\n  \}/);
  assert.ok(панель, 'метод buildPanel() должен существовать');
  const тело = панель[1];
  assert.doesNotMatch(тело, /class="seg-btn active" data-age="adult"/, 'взрослая не всегда активна');
  assert.match(тело, /data-age="adult"[\s\S]*?this\.ageCategory|this\.ageCategory[\s\S]*?data-age="adult"/);
  assert.match(тело, /id="opt-gaiters"[^>]*\$\{this\.gaiters/, 'галочка гетр идёт из состояния');
  assert.match(тело, /id="opt-qty"[^>]*value="\$\{this\.quantity\}"/, 'количество идёт из состояния');
});

// Главное в просьбе клиента — именно логотипы: «навставлял логотипов… обновил страницу,
// и у него всё сбрасывается». Лёгкий файл вставлялся как `blob:`, а такая ссылка живёт
// ровно до перезагрузки вкладки и в черновик не кладётся вообще. Значит все картинки
// приходят как data: — исходными байтами, без пережатия (у логотипов прозрачный фон).
test('логотип попадает в конструктор как data:, а не как blob:', () => {
  const метод = код.match(/\n  prepareImage\(file\)\s*\{([\s\S]*?)\n  \}/);
  assert.ok(метод, 'метод prepareImage() должен существовать');
  assert.match(метод[1], /readAsDataURL/, 'лёгкий файл читается в data: URL');
  assert.doesNotMatch(
    метод[1],
    /resolve\(\{ url: URL\.createObjectURL\(file\) \}\)/,
    'blob: URL умирает вместе со вкладкой и черновик его не переживёт'
  );
});

// Молчаливая потеря хуже отказа: покупатель обновит страницу и увидит форму без логотипа,
// решив, что конструктор сломался. Если логотип в черновик не влез — говорим прямо.
test('о непоместившемся логотипе покупателю сообщают, а не молчат', () => {
  assert.match(код, /id="draft-note"/, 'в панели должно быть место под сообщение о черновике');
  const метод = код.match(/\n  _saveDraft\(\)\s*\{([\s\S]*?)\n  \}/);
  assert.match(метод[1], /droppedImages/);
  assert.match(метод[1], /_renderDraftNote\(/, 'сообщение обновляется на каждой записи');
  const заметка = код.match(/\n  _renderDraftNote\([\s\S]*?\)\s*\{([\s\S]*?)\n  \}/);
  assert.ok(заметка, 'метод _renderDraftNote() должен быть определён');
  assert.match(заметка[1], /загруз/i, 'сообщение должно объяснять, что логотип придётся загрузить заново');
});
