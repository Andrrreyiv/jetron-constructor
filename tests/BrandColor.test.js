// Ручной цвет бренд-знака по расцветкам. Клиент 04.09 (голосовое): «наверное, надо вручную
// всё-таки проставлять, потому что бог его знает, какие там ещё формы и вариации будут,
// и что-нибудь заглючит, машину сделать чёрной, а нужно будет синий... давайте вручную
// настройку сделаем с ВЫБОРОМ ЦВЕТА ИЗ ПАЛИТРЫ».
//
// То есть просят НЕ «авто/белый/чёрный», а произвольный цвет. Автоматика остаётся режимом
// по умолчанию: 45 расцветок уже настроены ею, и обнулять их ручным выбором нельзя.
import { test } from 'node:test';
import assert from 'node:assert/strict';

import { цветЗнака, источникЗнака, ЦВЕТ_БЕЛЫЙ, ЦВЕТ_ЧЁРНЫЙ } from '../src/js/core/TextColor.js';
import { resolveBrandColor, brandEntryFromBox, validateOverrides } from '../src/js/core/ZoneOverrides.js';

test('без ручного цвета поведение прежнее: белый на тёмной ткани, чёрный на светлой и при неизвестной', () => {
  // Ровно те же три случая, что стерегут автоматику в TextColor.test.js. Ручная настройка
  // не имеет права их сдвинуть: иначе 45 уже согласованных расцветок поедут разом.
  assert.equal(цветЗнака(102, null), ЦВЕТ_БЕЛЫЙ);   // красный Winner, грудь
  assert.equal(цветЗнака(198, null), ЦВЕТ_ЧЁРНЫЙ);  // champion-white
  assert.equal(цветЗнака(null, null), ЦВЕТ_ЧЁРНЫЙ); // подложка не загрузилась
});

test('ручной цвет побеждает автоматику — ради этого клиент её и просил', () => {
  // Его пример дословно: автоматика «сделает чёрной, а нужно будет синий».
  assert.equal(цветЗнака(198, '#0033aa'), '#0033aa');
  // И наоборот: на тёмной ткани автоматика дала бы белый, а админ хочет свой цвет.
  assert.equal(цветЗнака(102, '#0033aa'), '#0033aa');
});

test('битый цвет НЕ роняет конструктор и НЕ красит знак мусором — откат на автоматику', () => {
  // zones.json правит человек через админку, и туда может попасть что угодно. Правило проекта:
  // неполные данные не роняют конструктор, а просто игнорируются (как в AdminOverrides).
  for (const мусор of ['', 'синий', '#fff', '#12345', 'rgb(0,0,0)', 123, {}, [], null, undefined]) {
    assert.equal(цветЗнака(102, мусор), ЦВЕТ_БЕЛЫЙ,
      `мусор ${JSON.stringify(мусор)} должен был откатиться на автоматику`);
  }
});

test('на белом и чёрном берём ГОТОВЫЙ файл, перекраска только для остальных цветов', () => {
  // Знак — две готовые PNG: плоский силуэт с жёсткой альфой (замерено 04.09: 109 283
  // непрозрачных пикселя, ВСЕ одного цвета, полупрозрачных ноль). Для белого и чёрного
  // перекрашивать нечего — берём готовый файл и получаем пиксель-в-пиксель то же, что до
  // этой правки. Это защищает все 45 нынешних расцветок от косметической регрессии.
  assert.deepEqual(источникЗнака(ЦВЕТ_БЕЛЫЙ), { файл: 'white', перекрасить: null });
  assert.deepEqual(источникЗнака(ЦВЕТ_ЧЁРНЫЙ), { файл: 'black', перекрасить: null });
  // Произвольный цвет: красим силуэт. Основой берём ЧЁРНЫЙ файл — непрозрачен он там же, где
  // белый, а операция source-in цвет исходника всё равно отбрасывает.
  assert.deepEqual(источникЗнака('#0033aa'), { файл: 'black', перекрасить: '#0033aa' });
});

test('цвет знака читается из той же записи zones.json, где лежит его позиция', () => {
  // Отдельного файла и отдельного эндпоинта заводить не стали: цвет ложится рядом с позицией
  // знака, в ту же запись, которую редактор зон уже умеет сохранять.
  const overrides = {
    'champion-white': { chest_brand: { x: 0.1, y: 0.2, w: 0.09, h: 0.033, color: '#0033aa' } },
    'new-teal': { chest_brand: { x: 0.1, y: 0.2, w: 0.09, h: 0.033 } }
  };
  assert.equal(resolveBrandColor(overrides, 'champion-white', 'chest_brand'), '#0033aa');
  // Цвет не задан — null, то есть «решай автоматикой», а не «крась чёрным».
  assert.equal(resolveBrandColor(overrides, 'new-teal', 'chest_brand'), null);
  // Своей записи нет вовсе (на 04.09 такова 44 расцветки из 45) — тоже автоматика.
  assert.equal(resolveBrandColor(overrides, 'winner-red', 'chest_brand'), null);
  assert.equal(resolveBrandColor(null, 'winner-red', 'chest_brand'), null);
  // Мусор из файла до конструктора не доходит.
  const битый = { 'x-1': { chest_brand: { x: 0, y: 0, w: 0.1, h: 0.1, color: 'синий' } } };
  assert.equal(resolveBrandColor(битый, 'x-1', 'chest_brand'), null);
});

test('перетаскивание знака в редакторе НЕ стирает выбранный цвет', () => {
  // Ловушка: редактор пишет session[form][brandKey] = box, то есть заменяет запись ЦЕЛИКОМ.
  // Админ выбрал синий, потом подвинул знак — и цвет молча исчез бы.
  const прежняя = { x: 0.1, y: 0.2, w: 0.09, h: 0.033, color: '#0033aa' };
  const новыйBox = { x: 0.5, y: 0.6, w: 0.09, h: 0.033 };
  assert.deepEqual(brandEntryFromBox(прежняя, новыйBox),
    { x: 0.5, y: 0.6, w: 0.09, h: 0.033, color: '#0033aa' });
  // Записи ещё не было — просто box, без пустого поля color в файле.
  assert.deepEqual(brandEntryFromBox(undefined, новыйBox), { x: 0.5, y: 0.6, w: 0.09, h: 0.033 });
  // Битый цвет из старого файла не переносим.
  assert.deepEqual(brandEntryFromBox({ ...прежняя, color: 'синий' }, новыйBox),
    { x: 0.5, y: 0.6, w: 0.09, h: 0.033 });
});

test('validateOverrides: цвет необязателен, но битый цвет отвергается на границе', () => {
  const позиция = { x: 0.1, y: 0.2, w: 0.09, h: 0.033 };
  assert.equal(validateOverrides({ f: { chest_brand: позиция } }).ok, true);
  assert.equal(validateOverrides({ f: { chest_brand: { ...позиция, color: '#0033aa' } } }).ok, true);
  // Строка не-цвет или число — признак испорченного файла. Лучше отказаться от всего zones.json
  // и остаться на базовом конфиге, чем красить знак наугад.
  assert.equal(validateOverrides({ f: { chest_brand: { ...позиция, color: 'синий' } } }).ok, false);
  assert.equal(validateOverrides({ f: { chest_brand: { ...позиция, color: 123 } } }).ok, false);
});
