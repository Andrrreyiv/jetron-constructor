// Сторож против дефекта, который клиент назвал 03.09: «Когда цвет выбираем, блоки начинают
// скакать». Замер на текущей сборке (headless, торможение картинок 300 мс, ПК 1366×768
// и телефон 412×900, все 15 свотчей) показал ТРИ симптома разом на КАЖДОМ клике по цвету:
//   • `.line-badge` (название линейки + «Скачать макет» + «В КАРТОЧКУ») ИСЧЕЗАЛА из DOM
//     на всё время загрузки нового WebP: 305-321 мс при торможении 300, ~1500 при 1500;
//   • свежий холст Fabric создавался 600×800 (`_displayWidth(1)` = 600, высота по 1200/900)
//     внутри карточки 501×465 — переросток тянул раскладку и карточка уезжала ВВЕРХ 83 → 69 px
//     и возвращалась (на телефоне 82 → 68);
//   • карточка стояла ПУСТОЙ: старая картинка стёрта, новая ещё грузится (снимок C:/tmp/jm).
// Размер самой карточки при этом уже не гулял — его починил PR #13 (`_applyCardSize` до `await`).
// То есть #13 вылечил РАЗМЕР, а мигание содержимого и сдвиг остались.
//
// Причина: обработчик цвета звал `buildViews()` БЕЗУСЛОВНО, а тот делает
// `viewsEl.innerHTML = ''` и пересоздаёт холсты. При смене расцветки состав видов обычно
// тот же самый, пересобирать нечего: `setBackground` подменяет фон уже ПОСЛЕ `await`,
// поэтому переиспользованный холст держит старую картинку до готовности новой — без пустоты.
//
// ⚠️ Тест читает ИСХОДНИК (как `PickerRedraw.test.js`): jsdom в проекте нет. Чистая функция
// решения проверяется по-настоящему, а её вызов в `buildViews()` — текстом, потому что
// именно возврат безусловной пересборки и есть тот способ сломать всё обратно.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { needsViewsRebuild } from '../src/js/core/ViewsRebuild.js';

const src = readFileSync(
  fileURLToPath(new URL('../src/js/ui/app.browser.js', import.meta.url)),
  'utf8'
).replace(/^\s*\/\/.*$/gm, ''); // комментарии вырезаем: в них всё это упоминается намеренно

test('холсты не пересобираются, когда состав видов и размеры не изменились', () => {
  const план = { key: 'composite', displayWidth: 600, maxHeight: 465 };

  assert.equal(needsViewsRebuild(null, план), true, 'первая сборка обязана состояться');
  assert.equal(needsViewsRebuild(план, { ...план }), false,
    'ничего не изменилось — пересборка запрещена, иначе вернётся пустая карточка на смене цвета');
  assert.equal(needsViewsRebuild(план, { ...план, key: 'front|back' }), true,
    'сменился состав видов (композит → перёд+спина) — холсты обязаны пересобраться');
  assert.equal(needsViewsRebuild(план, { ...план, displayWidth: 380 }), true,
    'сменилась ширина (поворот телефона, ресайз) — холсты обязаны пересобраться');
  assert.equal(needsViewsRebuild(план, { ...план, maxHeight: 300 }), true,
    'сменился бюджет высоты — холсты обязаны пересобраться');

  // Сама функция ничего не гарантирует, если её не звать: guard именно на это.
  const тело = src.slice(src.indexOf('buildViews() {'));
  assert.ok(/needsViewsRebuild\(/.test(тело.slice(0, тело.indexOf('\n  }'))),
    'buildViews() снова пересобирает холсты безусловно — вернётся мигание блоков на смене цвета');
});
