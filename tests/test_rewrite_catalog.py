# Высота кадра, на которой калиброван `zoneTemplate` в конфиге: до 30.08 все 45
# мокапов добивались белым до 1200, и доли зон меряли от неё.
ЭТАЛОН = 1200


def карта(**линейки):
    """Огрызок карты мокапов: линейка -> целевые имена (они же имена файлов)."""
    return {
        "lines": {
            l: {"files": {f"исходник-{i}.jpg": t for i, t in enumerate(цели)}}
            for l, цели in линейки.items()
        }
    }


class TestНаборыЗон:
    def test_доли_едут_за_высотой_кадра_линейки(self):
        """Зона задана долей ОТ ХОЛСТА, а холст перестал быть общим.

        Пиксели формы после перегона 30.08 не сдвинулись ни на один у всех 45
        файлов — сверено с git. Ушла только белая добивка снизу, то есть кадр
        стал короче: 1200 -> 992 у Champion. Значит доля по вертикали обязана
        вырасти во столько же раз, иначе номер уедет вверх на 68 px.
        По горизонтали не меняется ничего: ширина как была 900, так и осталась.
        """
        шаблон = [
            {"key": "back_number", "box": {"x": 0.635, "y": 0.365, "w": 0.19, "h": 0.13}}
        ]
        зона = наборы_зон(шаблон, {"Champion": (900, 992)})["Champion"][0]
        assert (зона["box"]["x"], зона["box"]["w"]) == (0.635, 0.19)
        assert зона["box"]["y"] == round(0.365 * ЭТАЛОН / 992, 4)
        assert зона["box"]["h"] == round(0.13 * ЭТАЛОН / 992, 4)


class TestПереопределенияКлиента:
    def test_чужой_кадр_остаётся_нетронутым(self):
        """Расстановку клиента переносим пересчётом, но только там, где знаем кадр.

        Он расставил зоны у двух форм Champion. `champion-white` — наша,
        кадр 992, множитель 1200/992 = 1.2097, ни одна зона за холст не выходит.
        А `champion-sinij3` он завёл сам через админку на своей картинке
        `konstruktor2.jpg`, которой нет ни в согласованном составе, ни у нас на
        диске. Пропорция у неё другая: тот же множитель выбрасывает три её зоны
        на шортах за нижний край (0.9265 -> 1.147). Поэтому форма с неизвестной
        высотой обязана вернуться как есть — молча испортить чужую расстановку
        хуже, чем оставить её нерабочей и спросить.
        """
        было = {
            "champion-white": {"shorts_brand": {"x": 0.3648, "y": 0.7345, "w": 0.0445, "h": 0.02}},
            "champion-sinij3": {"shorts_brand": {"x": 0.3639, "y": 0.9265, "w": 0.0452, "h": 0.0216}},
        }
        стало = пересчитать_переопределения(было, {"champion-white": 992})
        assert стало["champion-sinij3"] == было["champion-sinij3"]
        свои = стало["champion-white"]["shorts_brand"]
        assert (свои["x"], свои["w"]) == (0.3648, 0.0445)
        assert свои["y"] == round(0.7345 * ЭТАЛОН / 992, 4)
        assert свои["h"] == round(0.02 * ЭТАЛОН / 992, 4)


class TestРасстановкаНаборов:
    def test_каждая_форма_уходит_на_набор_своей_линейки(self):
        """Пересчитанные доли надо ещё и подсунуть форме.

        Движок берёт зоны так: `form.zones || config.zoneSets[form.zoneSet] ||
        config.zoneTemplate` (`app.browser.js:65-68`). Пока `zoneSet` у формы не
        проставлен, она падает на общий `zoneTemplate` — то есть на доли,
        калиброванные под холст 1200, и весь пересчёт проходит мимо.
        """
        c = конфиг("Star", "Волна")
        c["zoneTemplate"] = [
            {"key": "back_number", "box": {"x": 0.6, "y": 0.4, "w": 0.2, "h": 0.1}}
        ]
        расставить_наборы(c, {"Star": (900, 1110), "Волна": (900, 1031)})
        assert {f["line"]: f["zoneSet"] for f in c["forms"]} == {"Star": "Star", "Волна": "Волна"}
        assert c["zoneSets"]["Star"][0]["box"]["y"] == round(0.4 * ЭТАЛОН / 1110, 4)


class TestСоставИзКарты:
    def test_состав_берётся_из_карты_мокапов(self):
        """Карта мокапов — единственный источник правды по составу: в ней ровно те 45
        расцветок, что согласованы, и ровно те файлы, что прогнаны нормализацией.
        Держать второй список в коде — верный способ развести каталог с картинками."""
        c = rewrite(конфиг("Rich", "Star"), карта(Star=["Star белый"], Волна=["Волна голубая"]))
        assert [f["line"] for f in c["forms"]] == ["Star", "Волна"]

    def test_заводит_недостающую_расцветку_в_палитре(self):
        """Волна приносит голубой, которого в палитре конструктора не было.
        Без него форма встанет с пустым названием и без образца цвета в панели."""
        c = rewrite(конфиг("Star"), карта(Волна=["Волна голубая"]))
        цвета = {x["id"]: x["name"] for x in c["colors"]}
        assert цвета["lightblue"] == "Голубой"
        assert c["forms"][0]["color"] == "Голубой"

    def test_выкидывает_расцветку_без_единой_формы(self):
        """Коралловый был только у Legend, а клиент его снял — в каталоге он теперь
        ничей. Панель рисует ВСЮ палитру без фильтра (`app.browser.js`, `colors.map`),
        поэтому осиротевший цвет остаётся кликабельным образцом с «0 вариантов»."""
        c = конфиг("Legend")
        c["colors"].append({"id": "coral", "name": "Коралловый", "hex": "#ff7f60"})
        rewrite(c, карта(Legend=["Legend белая"]))
        assert [x["id"] for x in c["colors"]] == ["white"]

    def test_сохраняет_zoneSet_у_уцелевшей_формы(self):
        """Правка пересобирает формы заново, а у 12 из них выставлен `zoneSet:
        singleFront` — своя раскладка зон. Пересборка не должна её терять: расстановку
        зон клиент делает сам (голосовое 28.08), и обнулять его работу нельзя."""
        c = конфиг("Space")
        c["forms"][0]["zoneSet"] = "singleFront"
        rewrite(c, карта(Space=["Space белый"]))
        assert c["forms"][0].get("zoneSet") == "singleFront"

    def test_ненормализованная_форма_остаётся_на_прежней_картинке(self):
        """Champion и New ждут исходников от клиента (голосовое 28.08: «попробую
        растянуть... пришлю готовые файлы»). Переводить их на имя нормализованного
        файла заранее — значит выложить каталог с битыми превью у 11 расцветок."""
        c = конфиг("New")
        rewrite(c, карта(New=["New белая"]), готовые=set())
        assert c["forms"][0]["images"]["front"] == "New белая.png"

    def test_путь_картинки_идёт_за_форматом_нормализации(self):
        """Расширение в конфиге и расширение на диске задаются в РАЗНЫХ файлах,
        и разъехаться им ничего не мешает: имя цели в `mockup-map.json` дано без
        расширения намеренно. Разъедутся — конструктор молча покажет пустые
        превью у всех 45 расцветок, а тесты останутся зелёными.

        Поэтому путь собирается от `normalize_mockups.FORMAT`, а не от строкового
        литерала: 28.08 формат сменился с PNG на WebP (29 МБ -> 3.3 МБ), и это
        единственное место, где смена обязана отозваться.
        """
        c = конфиг("Space")
        rewrite(c, карта(Space=["Space белый"]))
        assert c["forms"][0]["images"]["front"] == f"assets/mockups/Space белый.{FORMAT.lower()}"


def конфиг(*линейки):
    """Огрызок конфига: только то, что правка трогает."""
    return {
        "colors": [{"id": "white", "name": "Белый", "hex": "#f2f4f7"}],
        "catalog": {"lineSlugs": {l: l.lower() for l in линейки}},
        "forms": [
            {
                "id": f"{l.lower()}-white",
                "line": l,
                "colorId": "white",
                "color": "Белый",
                "colorHex": "#f2f4f7",
                "images": {"front": f"{l} белая.png", "back": f"{l} белая.png", "shoulder": None},
            }
            for l in линейки
        ],
    }


class TestRewrite:
    def test_убирает_rich_целиком(self):
        """Клиент снял Rich с производства 22.08. Линейки нет в карте — значит она
        уходит и из расцветок, и из ссылок на каталог, иначе плашка поведёт
        покупателя в пустой раздел."""
        c = rewrite(конфиг("Rich", "Star"), карта(Star=["Star белый"]))
        assert [f["line"] for f in c["forms"]] == ["Star"]
        assert "Rich" not in c["catalog"]["lineSlugs"]

    def test_переименовывает_venom_в_фаворит(self):
        """Venom пропал из магазина, но остался в конструкторе; клиент решил
        22.08 сделать его Фаворитом. Расцветки те же, меняется только имя —
        поэтому и `id` обязан перестать врать, что это Venom."""
        c = rewrite(конфиг("Venom"), карта(Фаворит=["Фаворит белая"]))
        форма = c["forms"][0]
        assert форма["line"] == "Фаворит"
        assert форма["id"] == "favorit-white"
        assert "Venom" not in c["catalog"]["lineSlugs"]
        assert c["catalog"]["lineSlugs"]["Фаворит"] == "favorit"
