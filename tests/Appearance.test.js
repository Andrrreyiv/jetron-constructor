// Внешний вид сцены из админки: фон, рамки, отступы.
//
// Клиент 13.09 голосовым: «скажите просто, где настраиваются вот эти все параметры… я попробую
// сам подвигать, так быстрее». До этого дня ответ был «нигде»: значения стояли числами в
// `stand.css`. Раздел «Внешний вид» даёт их ему в руки — и вместе с ними возможность вписать
// туда мусор. Отсюда главное требование этих тестов: битое значение НЕ должно ронять вёрстку,
// оно молча выбрасывается, а поле остаётся на умолчании из CSS.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import {
  ПОЛЯ_ВИДА, ПРЕДЕЛ_ОТСТУПА, корректныйЦветВида, корректныйОтступ,
  проверитьВид, видВПеременные, применитьВид,
} from '../src/js/core/Appearance.js';

test('цвет принимается только как #rrggbb или прозрачный', () => {
  for (const годный of ['#ffffff', '#FDF9EF', ' #112233 ', 'transparent']) {
    assert.equal(корректныйЦветВида(годный), true, годный);
  }
  for (const мусор of ['red', '#fff', '#12345', 'rgb(0,0,0)', '', null, 12, 'url(x)']) {
    assert.equal(корректныйЦветВида(мусор), false, String(мусор));
  }
});

// `expression()`/`url()` в значении CSS-переменной — классический способ протащить постороннее.
// Проверка цвета их не пропускает, и это важнее удобства.
test('в цвет нельзя протащить произвольный CSS', () => {
  const вид = проверитьВид({ stageBg: 'url(https://example.com/x.png)' });
  assert.equal('stageBg' in вид, false);
  assert.deepEqual(видВПеременные({ stageBg: 'red; position:fixed' }), {});
});

test('отступ — целое от нуля до потолка, остальное отбрасывается', () => {
  for (const годный of [0, 12, 40, ПРЕДЕЛ_ОТСТУПА, '28']) {
    assert.equal(корректныйОтступ(годный), true, String(годный));
  }
  for (const мусор of [-1, ПРЕДЕЛ_ОТСТУПА + 1, 12.5, 'много', '', null, NaN, Infinity]) {
    assert.equal(корректныйОтступ(мусор), false, String(мусор));
  }
});

// Главная страховка: незаполненное поле означает «не трогай», а не «поставь ноль».
test('пустой раздел ничего не переопределяет', () => {
  assert.deepEqual(проверитьВид(undefined), {});
  assert.deepEqual(проверитьВид(null), {});
  assert.deepEqual(проверитьВид({}), {});
  assert.deepEqual(видВПеременные({ stageBg: '', padTop: null }), {});
});

test('битое поле выбрасывается, соседнее годное применяется', () => {
  const вид = проверитьВид({ stageBg: '#ffffff', stageBorder: 'чёрный', padTop: 400, padSide: 10 });
  assert.deepEqual(вид, { stageBg: '#ffffff', padSide: 10 });
});

test('переменные собираются с единицами и по именам из списка полей', () => {
  const vars = видВПеременные({ stageBg: '#FFFFFF', cardBg: 'transparent', padTop: 16 });
  assert.deepEqual(vars, {
    '--stage-bg': '#ffffff',
    '--card-bg': 'transparent',
    '--stage-pad-top': '16px',
  });
});

// Тень — тумблер, а не цвет: значение берётся токеном, чтобы сама тень оставалась описанной
// в CSS одним местом и не размножалась по коду.
test('тень карточки переключается, а не задаётся числами', () => {
  assert.equal(видВПеременные({ cardShadow: true })['--card-shadow'], 'var(--sh-md)');
  assert.equal(видВПеременные({ cardShadow: false })['--card-shadow'], 'none');
  assert.equal(видВПеременные({ cardShadow: false })['--card-shadow-hover'], 'none');
  assert.equal('--card-shadow' in видВПеременные({ cardShadow: 'да' }), false, 'строка — не тумблер');
});

// Список полей — единственный источник правды и для формы в админке, и для применения.
test('каждое поле списка умеет превратиться в переменную', () => {
  for (const поле of ПОЛЯ_ВИДА) {
    const vars = видВПеременные({ [поле.ключ]: поле.умолчание });
    assert.ok(поле.css in vars, `поле ${поле.ключ} не дало переменную ${поле.css}`);
    assert.ok(поле.подпись && поле.подпись.length > 2, `у ${поле.ключ} нет подписи для админки`);
  }
});

test('применение ставит только заданные переменные и не падает без document', () => {
  const поставлено = {};
  const корень = { style: { setProperty: (k, v) => { поставлено[k] = v; } } };
  применитьВид({ stageBg: '#000000', padSide: 0, cardBorder: 'мусор' }, корень);
  assert.deepEqual(поставлено, { '--stage-bg': '#000000', '--stage-pad-side': '0px' });
  assert.deepEqual(применитьВид({ stageBg: '#000000' }, null) && true, true, 'без узла не роняем стенд');
});

// 🔴 Список полей продублирован в двух языках: `ПОЛЯ_ВИДА` здесь и `jetron_admin_view_fields()`
// в mu-плагине. Он и не может быть один — форму рисует PHP, а применяет CSS-переменные браузер.
// Зато разъехаться он не должен: тогда админ меняет поле, которого покупатель не видит, и это
// не проявится ни ошибкой, ни падением. Тест держит их вместе.
test('список полей и потолок отступа совпадают с mu-плагином админки', () => {
  const php = readFileSync(new URL('../deploy/jetron-admin.php', import.meta.url), 'utf8');
  const ключиPHP = [...php.matchAll(/array\('key' => '(\w+)'/g)].map((m) => m[1]);
  assert.deepEqual(ключиPHP, ПОЛЯ_ВИДА.map((п) => п.ключ),
    'поля админки и поля конструктора разошлись');

  const потолок = php.match(/JETRON_VIEW_PAD_MAX = (\d+)/);
  assert.ok(потолок, 'в плагине должен быть потолок отступа');
  assert.equal(Number(потолок[1]), ПРЕДЕЛ_ОТСТУПА, 'потолки отступа разошлись');

  // Проверка цвета в PHP обязана быть такой же строгой: короткий #fff конструктор не примет,
  // и значение молча потерялось бы уже у покупателя.
  assert.match(php, /\^#\[0-9a-fA-F\]\{6\}\$/, 'в плагине ослабили проверку цвета');
  assert.match(php, /'transparent'/, 'в плагине потеряли прозрачный');
});
