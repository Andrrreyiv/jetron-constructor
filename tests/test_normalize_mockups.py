# -*- coding: utf-8 -*-
"""Контракт нормализации мокапов.

Смысл нормализации не в том, чтобы получить файлы одного размера — это следствие.
Смысл в том, чтобы форма во всех кадрах ОДНОЙ ЛИНЕЙКИ встала в одну и ту же
геометрическую рамку. Зоны нанесения заданы долями 0..1 от холста, а расставляет их
клиент один раз на линейку — значит и рамка обязана совпадать в пределах линейки.

⚠️ Высота холста в конструкторе НЕ жёсткая: `setBackground` вписывает картинку по ширине
и следом двигает высоту холста под неё (canvas.browser.js:49-59, проверено живым браузером
29.08 — фон 1100x1200 увёл высоту 800 -> 654.5 при ширине 600). Поэтому белая полоса под
шортами бралась не из «неподходящей пропорции картинки», а из того, что мы сами добивали
кадр белым до 1200. Высота кадра считается по линейке, а не берётся константой.

Поэтому здесь проверяется именно рамка, а не «картинка открылась».
"""
import sys
from pathlib import Path

import numpy as np
import pytest
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))

from normalize_mockups import (  # noqa: E402
    BOTTOM_PX,
    CANVAS_WIDTH,
    TOP_PX,
    fitted_height,
    frame,
    ink_bbox,
    line_canvas,
    normalize,
    plan,
    save_mockup,
)


def canvas_with(box, size=(1920, 1920), fill=(20, 30, 200)):
    """Белый кадр с одним тёмным прямоугольником — подделка формы на белом фоне."""
    im = Image.new("RGB", size, "white")
    im.paste(Image.new("RGB", (box[2] - box[0], box[3] - box[1]), fill), (box[0], box[1]))
    return im


КАРТА = {
    "_": "служебный ключ верхнего уровня",
    "_source_dir": "C:/тест",
    "lines": {
        "Winner": {
            "_batch": "служебный ключ внутри линейки",
            "files": {"a.jpg": "Winner белый", "b.jpg": "Winner синий"},
        },
        "Волна": {
            "_names_provisional": "имена придуманы нами",
            "files": {"c.jpg": "Волна красная"},
        },
    },
}


class TestPlan:
    def test_разворачивает_карту_в_задачи_без_служебных_ключей(self):
        """Ключи с подчёркиванием — комментарии для человека, а не файлы.
        Взять их за исходники значит уронить прогон на несуществующем пути."""
        задачи = plan(КАРТА)
        assert [(t["line"], t["target"]) for t in задачи] == [
            ("Winner", "Winner белый"),
            ("Winner", "Winner синий"),
            ("Волна", "Волна красная"),
        ]


class TestInkBbox:
    def test_находит_рамку_краски_на_белом(self):
        a = np.asarray(canvas_with((100, 200, 500, 900)), "uint8")
        assert ink_bbox(a) == (100, 200, 499, 899)

    def test_накрывает_перёд_и_зад_одной_рамкой(self):
        """В кадре поставщика слева перёд, справа зад. Резать пополам нельзя —
        клиент это опроверг 23.08. Рамка обязана накрыть оба объекта сразу."""
        im = canvas_with((100, 200, 500, 900))
        im.paste(Image.new("RGB", (400, 700), (20, 30, 200)), (900, 250))
        a = np.asarray(im, "uint8")
        assert ink_bbox(a) == (100, 200, 1299, 949)

    def test_не_ведётся_на_одиночный_шум_jpeg(self):
        """У сжатого JPEG в белом поле попадаются одиночные тёмные точки.
        Клюнуть на них — значит растянуть рамку на весь кадр и запороть масштаб."""
        im = canvas_with((100, 200, 500, 900))
        im.putpixel((5, 5), (100, 100, 100))
        im.putpixel((1900, 1900), (100, 100, 100))
        a = np.asarray(im, "uint8")
        assert ink_bbox(a) == (100, 200, 499, 899)

    def test_видит_белую_форму_по_контуру(self):
        """Белые расцветки есть в шести линейках. Полотно почти сливается с фоном,
        но контур и тень всегда темнее — на них и держится рамка."""
        im = Image.new("RGB", (1920, 1920), "white")
        im.paste(Image.new("RGB", (400, 700), (200, 200, 200)), (100, 200))
        im.paste(Image.new("RGB", (396, 696), (252, 252, 252)), (102, 202))
        a = np.asarray(im, "uint8")
        assert ink_bbox(a) == (100, 200, 499, 899)


class TestВерхняяПолоса:
    """Клиент 2026-08-29: «форма задевает плашку, надо пространство сверху под рабочие зоны».

    Плашка линейки и кнопка «перейти в карточку» стоят абсолютом от верха холста
    (`.line-badge` в stand.css) и занимают ~34 px при ширине холста 626, то есть
    примерно 65 px в координатах холста 900x1200. Полоса обязана быть шире этого,
    иначе форма снова упрётся в плашку.
    """

    ВЫСОТА_ПЛАШКИ = 65

    def test_полоса_вмещает_плашку_и_кнопку(self):
        assert TOP_PX > self.ВЫСОТА_ПЛАШКИ

    def test_высота_кадра_считается_по_самой_высокой_форме_линейки(self):
        """Правка 29.08. Раньше кадр был жёстко 900x1200 и у линеек с низкой формой
        под шортами оставалась белая полоса. Клиент показал скриншотами, что окно
        подстраивается под картинку, — значит полосу рисовали мы сами."""
        низкая = (0, 0, 899, 673)   # 900x674, как у Champion
        высокая = (0, 0, 899, 853)  # 900x854, как у Star
        assert line_canvas([низкая, высокая]) == (CANVAS_WIDTH, 854 + TOP_PX + BOTTOM_PX)


class TestFrame:
    def test_форма_вписана_по_ширине_кадра(self):
        """Масштаб задаёт ШИРИНА, а не высота: пара «перёд + зад» шире, чем выше.
        Высоту не подгоняем ни под какую долю — иначе форму пришлось бы искажать
        или резать, а обе расцветки одной линейки поехали бы друг относительно друга."""
        bbox = (0, 0, 580, 1000)
        f = frame(bbox, canvas=line_canvas([bbox]))
        assert f["width"] == CANVAS_WIDTH
        assert f["height"] == pytest.approx(fitted_height(bbox), abs=1)

    def test_центрируется_по_горизонтали(self):
        bbox = (0, 0, 580, 1000)
        f = frame(bbox, canvas=line_canvas([bbox]))
        assert f["left"] == pytest.approx((CANVAS_WIDTH - f["width"]) / 2, abs=1)

    def test_расцветки_одной_линейки_садятся_в_один_верх(self):
        """Главный инвариант, и он про ВЕРХ, а не про высоту.

        Плечи у всех расцветок линейки обязаны встать на одной строке: номер и
        логотипы клиент ставит один раз на линейку, и переключение цвета не должно
        их двигать. Верх даёт `top_px`, ширину — кадр, обе величины общие.

        А вот высоту равнять нельзя. Разброс внутри линейки (Champion 674..736 px)
        — это зазор поставщика между передом и задом и то, сколько попало гетр
        и бутс. Подогнать высоту значило бы растянуть одни шорты ради других."""
        узкая = (0, 0, 480, 1000)
        широкая = (0, 0, 620, 1000)
        кадр = line_canvas([узкая, широкая])
        assert frame(узкая, canvas=кадр)["top"] == frame(широкая, canvas=кадр)["top"]
        assert frame(узкая, canvas=кадр)["width"] == frame(широкая, canvas=кадр)["width"]

    def test_высокую_форму_не_выпускает_за_нижний_край(self):
        """Страховка на исходник небывалой пропорции.

        Все 45 кадров упираются шириной, поэтому клапан по высоте не срабатывает
        ни разу. Но если поставщик пришлёт вытянутый кадр, форма обязана остаться
        внутри рабочей полосы: лучше она встанет мельче обещанного, чем вылезет
        за низ карточки и обрежется."""
        f = frame((0, 0, 499, 1999), canvas=(CANVAS_WIDTH, 706))
        assert f["top"] + f["height"] <= 706 - BOTTOM_PX
        assert f["width"] <= CANVAS_WIDTH
        assert f["left"] >= 0


class TestNormalize:
    def test_отдаёт_ровно_кадр_линейки(self):
        кадр = line_canvas([ink_bbox(np.asarray(canvas_with((100, 200, 500, 900)), "uint8"))])
        assert normalize(canvas_with((100, 200, 500, 900)), canvas=кадр).size == кадр

    def test_ставит_форму_в_обещанную_рамку(self):
        """Сквозная проверка: то, что посчитал frame, реально оказалось на картинке."""
        src = canvas_with((100, 200, 500, 900))
        box = ink_bbox(np.asarray(src, "uint8"))
        кадр = line_canvas([box])
        ожидание = frame(box, canvas=кадр)
        got = ink_bbox(np.asarray(normalize(src, canvas=кадр), "uint8"))
        assert got[1] == pytest.approx(ожидание["top"], abs=2)
        assert got[3] - got[1] + 1 == pytest.approx(ожидание["height"], abs=2)

    def test_разные_пропорции_садятся_в_один_верх(self):
        """Тот же инвариант, что и в TestFrame, но уже на пикселях, а не на
        арифметике: проверяем готовую картинку, а не намерение.

        Обе расцветки идут в ОДИН кадр линейки — так их и увидит клиент,
        переключая цвет."""
        узкая = canvas_with((100, 200, 480, 1200))
        широкая = canvas_with((700, 50, 1320, 1050))
        кадр = line_canvas(
            [ink_bbox(np.asarray(im, "uint8")) for im in (узкая, широкая)]
        )
        a = ink_bbox(np.asarray(normalize(узкая, canvas=кадр), "uint8"))
        b = ink_bbox(np.asarray(normalize(широкая, canvas=кадр), "uint8"))
        assert a[1] == pytest.approx(b[1], abs=2)
        assert a[0] == pytest.approx(b[0], abs=2)
        assert a[2] == pytest.approx(b[2], abs=2)


class TestSaveMockup:
    def test_сохраняет_в_webp_а_не_в_png(self, tmp_path):
        """Мокап — фотография, а PNG её не жмёт: замер 28.08 на пяти худших дал
        514-837 КБ, то есть 45 файлов = около 30 МБ на мобильном интернете, и 18
        файлов вылетели за бюджет приёмки в 600 КБ.

        WebP q92 на тех же пяти: 75-137 КБ при RMSE 1.1-2.3 из 255 — разницы
        глазом нет, вес падает вшестеро. JPEG q92 хуже по обоим показателям
        (107-162 КБ, RMSE 1.4-2.6). WebP в проекте уже проверен: `Rich белая.webp`
        лежал в боевом наборе и открывался.

        Формат — часть контракта приёмки, а не деталь реализации: имя цели в
        `mockup-map.json` даётся без расширения, и подставляет его именно эта
        функция, поэтому промах здесь молча разошёлся бы с путями в конфиге.
        """
        src = canvas_with((100, 200, 500, 900))
        кадр = line_canvas([ink_bbox(np.asarray(src, "uint8"))])
        dst = save_mockup(normalize(src, canvas=кадр), tmp_path / "Champion белый")
        assert dst.suffix == ".webp"
        with Image.open(dst) as saved:
            assert saved.format == "WEBP"
            assert saved.size == кадр
