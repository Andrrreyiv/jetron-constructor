# -*- coding: utf-8 -*-
"""Сторож на том же стыке, что и `test_frame_aspect.py`: доли зон в конфиге против
мокапов на диске.

Зона задана ДОЛЕЙ от холста, а холст повторяет кадр мокапа. Значит любая пересборка
картинок (`run_normalize.py`, новый исходник от клиента, смена `TOP_PX`) молча
обесценивает `zoneSets` в `mock-config.json`: числа в конфиге остаются от прежнего
кадра, а делятся теперь на новый.

⚠️ Опасность не теоретическая, она СРАБОТАЛА. 03.09 клиент прислал композит
`Star чёрный`, `run_normalize.py` прогнали (кадр Star 954 -> 878, коммит `4e51a67`),
а `rewrite_catalog.py` — нет. Конфиг последний раз трогали 01.09 (`0b5de84`), и все
десять зон линейки Star остались посчитанными на кадр 954: на демо они уезжали вверх
на 18.6..60.1 px и были на 3.6..12.5 px мельче нужного, на всех ПЯТИ расцветках Star.
Ни один из 93 JS-тестов и 41 pytest этого не видел — они проверяют формулу на
синтетике, а не то, что записано в боевом конфиге.

Тест держит инвариант: `zoneSets[линейка]` обязан быть равен `наборы_зон()` от
`zoneTemplate` и НАСТОЯЩЕЙ высоты кадра этой линейки. Ломается ровно тогда, когда
картинки пересобрали, а каталог не переписали.
"""
import json
import sys
from pathlib import Path

import pytest
from PIL import Image

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "scripts"))

from normalize_mockups import СДВИГ_ФОРМЫ  # noqa: E402
from rewrite_catalog import ЭТАЛОННАЯ_ВЫСОТА, наборы_зон  # noqa: E402

КОНФИГ = КОРЕНЬ / "src" / "config" / "mock-config.json"


def _конфиг():
    return json.loads(КОНФИГ.read_text(encoding="utf-8"))


def _кадры_с_диска(config):
    """Линейка -> (ширина, высота) по РЕАЛЬНЫМ файлам расцветок этой линейки.

    Читаем не имя файла и не запись в конфиге, а пиксели: именно расхождение
    «в конфиге одно, на диске другое» этот тест и ловит. Внутри линейки кадр
    один — на этом стоит и размножение зон донор -> линейка.
    """
    кадры = {}
    for форма in config["forms"]:
        for путь in форма.get("images", {}).values():
            if not isinstance(путь, str):
                continue
            файл = КОРЕНЬ / путь.lstrip("/")
            if not файл.exists():
                pytest.skip(f"мокап {путь} не собран")
            кадры.setdefault(форма["line"], set()).add(Image.open(файл).size)
    if not кадры:
        pytest.skip("мокапы не собраны")
    разъехались = {л: sorted(р) for л, р in кадры.items() if len(р) != 1}
    assert not разъехались, (
        f"внутри линейки разные кадры: {разъехались}. Зоны копировать по линейке "
        "больше нельзя — пересобрать мокапы."
    )
    return {л: next(iter(р)) for л, р in кадры.items()}


def test_zonesets_в_конфиге_пересчитаны_под_кадры_на_диске():
    config = _конфиг()
    кадры = _кадры_с_диска(config)
    ожидаемые = наборы_зон(
        config["zoneTemplate"], кадры, эталон=ЭТАЛОННАЯ_ВЫСОТА, сдвиг=СДВИГ_ФОРМЫ
    )

    промахи = []
    for линейка, зоны in ожидаемые.items():
        записанные = {з["key"]: з["box"] for з in config["zoneSets"][линейка]}
        высота = кадры[линейка][1]
        for зона in зоны:
            было = записанные[зона["key"]]
            надо = зона["box"]
            for поле in ("x", "y", "w", "h"):
                сдвиг_px = (было[поле] - надо[поле]) * высота
                if abs(сдвиг_px) >= 0.5:
                    промахи.append(
                        f"{линейка}/{зона['key']}.{поле}: в конфиге {было[поле]}, "
                        f"по кадру {высота} надо {надо[поле]} ({сдвиг_px:+.1f} px)"
                    )

    assert not промахи, (
        "zoneSets отстали от мокапов — прогнать `python scripts/run_normalize.py` "
        "и переписать каталог `rewrite_catalog.py`:\n  " + "\n  ".join(промахи)
    )
