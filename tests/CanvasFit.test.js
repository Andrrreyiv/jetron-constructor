import { test } from 'node:test';
import assert from 'node:assert/strict';
import { capWidthByHeight } from '../src/js/core/CanvasFit.js';

// Клиент 31.08: «на ноутбуке конструктор должен помещаться без вертикальной прокрутки».
// Замер 1366×768 до правки: холст вписывался ТОЛЬКО по ширине (600 px → высота 661 px по
// пропорции мокапа 900×992), и страница переливалась на 250 px. Ширину обязана ограничивать
// и высота тоже, иначе критерий приёмки не выполняется ни на одной линейке.
test('ширина холста ограничена доступной высотой, а когда та не мешает — не трогается', () => {
  const champion = 992 / 900; // самая низкая линейка
  const star = 1110 / 900; // самая высокая

  // Влезает по ширине, но не влезает по высоте: 600 × 1.1022 = 661 px при бюджете 460.
  assert.equal(capWidthByHeight(600, champion, 460), 417);
  // Пропорция выше — та же высота даёт более узкий холст.
  assert.equal(capWidthByHeight(600, star, 460), 372);
  // Бюджета хватает: ширину не уменьшаем, крупная форма остаётся крупной.
  assert.equal(capWidthByHeight(600, champion, 800), 600);
  // Бюджета нет вовсе — не уходим в ноль и не отдаём отрицательное.
  assert.equal(capWidthByHeight(600, champion, 0), 150);
});
