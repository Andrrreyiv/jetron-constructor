// Что держит первую отрисовку конструктора, а что нет.
//
// Клиент 15.09: «Очень долгая загрузка конструктора, я бы конечно давно ушёл со страницы».
// Замеры боевого в тот же день, по ним и написаны все проверки ниже:
//
//   1. В `loadFonts()` стоял `await face.load()` ВНУТРИ цикла — 23 промежутка из 24 шли
//      последовательно. Исправлено на параллель, но одного этого НЕ ХВАТИЛО: холст как
//      появлялся около секунды, так и появлялся.
//   2. Настоящая цена шрифтов вскрылась на мобильном канале (1,6 Мбит/с, задержка 150 мс):
//      холст на 12 967 мс, а с заблокированными шрифтами — на 5 418 мс. Разница 7,5 с.
//      Сайт на h2, лимита соединений нет: 1,79 МБ шрифтов отнимали ПОЛОСУ у мокапа в 75 КБ.
//      Отсюда ленивая загрузка: на старте только шрифты черновика, остальные — по требованию.
//   3. Цены каталога держали холст: `admin-ajax.php?action=jetron_prices` длится 532 мс,
//      и мокап уходил в сеть лишь на 1815 мс, хотя весь критический путь — 438 мс.
//      Ни `renderAll`, ни `renderJetron` цен не читают, поэтому они уехали в фон.
//
// ⚠️ Тест читает ИСХОДНИК: jsdom в проекте нет, а `FontFace` и порядок сетевых запросов
// иначе не проверить. Он ловит ровно те способы сломать это, которыми уже ломали.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const код = readFileSync(new URL('../src/js/ui/app.browser.js', import.meta.url), 'utf8');
const тело = (сигнатура, имя) => {
  const m = код.match(new RegExp(`\\n  async ${сигнатура}\\s*\\{([\\s\\S]*?)\\n  \\}`));
  assert.ok(m, `метод ${имя} должен существовать`);
  return m[1];
};
const старт = () => тело('start\\(\\)', 'start()');

test('шрифты грузятся параллельно, а не очередью', () => {
  const t = тело('loadFonts\\(ids = null\\)', 'loadFonts(ids)');
  assert.match(t, /Promise\.all\(/, 'параллельная загрузка пропала');
  assert.doesNotMatch(t, /for \([\s\S]*await face\.load\(\)/,
    'await внутри цикла — та самая очередь, 23 промежутка из 24');
});

// Главное: 7,5 секунды на мобильном. На старте грузим только шрифты черновика.
test('на старте грузятся только шрифты черновика, а не все 23', () => {
  const t = старт();
  assert.match(t, /this\.loadFonts\(this\._шрифтыЧерновика\(\)\)/,
    'вернулась загрузка всех шрифтов на старте — это 7,5 с на телефоне');
  assert.doesNotMatch(t, /this\.loadFonts\(\)\s*;/, 'loadFonts() без списка на старте — это все 23');
  // `_шрифтыЧерновика` — обычный метод, не async, поэтому проверяем его по всему исходнику.
  assert.match(код, /_шрифтыЧерновика\(\)\s*\{[\s\S]*optCache[\s\S]*fontId/,
    'список шрифтов черновика должен собираться из optCache');
});

test('повторные вызовы не грузят одно и то же дважды', () => {
  const t = тело('loadFonts\\(ids = null\\)', 'loadFonts(ids)');
  assert.match(t, /fontsReady\.includes\(f\.id\)/, 'уже загруженные обязаны отсеиваться');
  assert.match(t, /_шрифтыВПути/, 'летящие запросы обязаны переиспользоваться, а не дублироваться');
});

// Цены каталога — 532 мс до того, как вообще будет запрошен мокап. Холст их не ждёт.
test('цены каталога ушли в фон и не держат холст', () => {
  const t = старт();
  assert.match(t, /const цены = this\.loadCatalogPrices\(\);/, 'цены должны стартовать без await');
  assert.doesNotMatch(t, /await this\.loadCatalogPrices\(\)/, 'ожидание цен возвращает задержку 532 мс');
  assert.ok(t.indexOf('await this.renderAll()') < t.indexOf('this.buildPanel()'),
    'холст обязан рисоваться РАНЬШЕ сборки панели');
});

// applyColorHexes внутри loadCatalogPrices красит кружки и рассчитан на то, что идёт
// до buildColorPicker. Раз цены теперь позже — палитру обязаны перерисовать.
test('после прихода цен палитра перекрашивается, а возраст уточняется', () => {
  const t = старт();
  const после = t.indexOf('цены.then(');
  assert.ok(после > 0, 'подписка на приход цен пропала');
  for (const вызов of ['this.buildColorPicker()', 'this.renderSizeBar()', 'this.updatePrice()']) {
    assert.ok(t.indexOf(вызов, после) > после, `после цен обязан идти ${вызов}`);
  }
});

// Монограмму ставит renderJetron во время первой отрисовки — она единственная осталась
// на критическом пути, и две её картинки обязаны грузиться парой, а не цепочкой.
test('монограмма ждётся перед отрисовкой и грузится в две руки', () => {
  const t = старт();
  assert.match(t, /await this\.loadBranding\(\);/, 'монограмма нужна renderJetron до отрисовки');
  const b = тело('loadBranding\\(\\)', 'loadBranding()');
  assert.match(b, /Promise\.all\(\[/, 'два await подряд стоили 300 мс на боевом');
});

test('после прихода шрифтов текст перерисовывается один раз и после стартовой отрисовки', () => {
  const t = старт();
  const перерисовка = t.indexOf('шрифты.then(');
  assert.ok(перерисовка > 0, 'перерисовка по готовности шрифтов пропала');
  assert.ok(перерисовка > t.indexOf('await this.renderAll()'),
    'подписка обязана стоять НИЖЕ стартовой отрисовки: защиты от одновременных renderAll нет');
  assert.match(t, /шрифты\.then\(\(\) => this\.renderAll\(\{ keepCards: true \}\)\)/,
    'карточки не пересобираем: образцы в палитре подхватят шрифт сами, это делает CSS');
});

// Раз на старте шрифтов нет, палитра обязана догрузить их сама — иначе покупатель увидит
// список образцов, нарисованных одним и тем же sans-serif.
test('палитра шрифтов догружает их при раскрытии, а выбор ждёт свой шрифт', () => {
  // 19.09 крючок переехал с `details.opt-font` на кнопку «Шрифт» — суть та же.
  assert.match(код, /\.opt-fc-btn/, 'крючок на раскрытие палитры пропал');
  assert.match(код, /палитра === 'font'\) this\.loadFonts\(\)/,
    'при раскрытии панели «Шрифт» обязаны догружаться все шрифты');
  assert.match(код, /_палитраОткрыта\(opt\.id\) === 'font'\) this\.loadFonts\(\)/,
    'панель, раскрытая с прошлой отрисовки, обязана догрузить шрифты сама');
  assert.match(код, /this\.loadFonts\(\[b\.dataset\.font\]\)[\s\S]{0,120}renderAll\(\{ keepCards: true \}\)/,
    'выбранный шрифт мог не приехать: дожидаемся именно его и перерисовываем');
});

// ── Дефект 18.09: в заказе «шрифт: РПЛ», а нарисован системный sans ────────────────────
// Клиент голосовым: «начинаешь забивать фамилию и номер — РПЛ не применяется… надо нажать
// на RPL, и тогда применится». Ленивая загрузка 15.09 собирала стартовый список из одного
// optCache, где `fontId` появляется ТОЛЬКО после клика по палитре. Покупатель, оставивший
// шрифт по умолчанию, палитру не открывает — FontFace `rpl` не регистрировался вовсе, холст
// падал на sans-serif, а спецификация печатала «РПЛ» по идентификатору. Уехало в боевой заказ.
const телоБезAsync = (имя, ярлык) => {
  const m = код.match(new RegExp(`\\n  ${имя}\\(\\)\\s*\\{([\\s\\S]*?)\\n  \\}`));
  assert.ok(m, `метод ${ярлык} должен существовать`);
  return m[1];
};

test('шрифт по умолчанию грузится на старте, даже когда покупатель его не выбирал', () => {
  const t = телоБезAsync('_шрифтыЧерновика', '_шрифтыЧерновика()');
  assert.match(t, /new Set\(\[this\.defaultFontId\(\)\]\)/,
    'дефолтный шрифт обязан быть в списке ВСЕГДА: в optCache его нет, пока не ткнули в палитру');
});

test('сведение макета дожидается шрифтов, которыми оно нарисовано', () => {
  const t = тело('_composeMockupCanvas\\(\\)', '_composeMockupCanvas()');
  assert.match(t, /await this\.loadFonts\(this\._шрифтыМакета\(\)\)/,
    'PNG заказа обязан ждать свои шрифты: иначе в печать уедет чужой');
  assert.match(t, /fontsReady[\s\S]{0,200}renderAll\(\{ keepCards: true \}\)/,
    'доехавший шрифт обязан попасть на холст ДО toDataURL, иначе ожидание бессмысленно');
  assert.ok(t.indexOf('await this.loadFonts(') < t.indexOf('view.toDataURL()'),
    'ожидание шрифтов обязано стоять ДО снятия картинок с холстов');
});

test('список шрифтов макета собирается по фактической отрисовке', () => {
  const t = телоБезAsync('_шрифтыМакета', '_шрифтыМакета()');
  assert.match(t, /this\.resolveFont\(p\.fontId, p\.value\)/,
    'шрифт надо брать через resolveFont: он откатывает латинский клубный на РПЛ при кириллице');
  assert.match(t, /new Set\(\[this\.defaultFontId\(\)\]\)/,
    'неявный дефолт обязан попадать и сюда');
});

// ── Две кнопки «Шрифт» и «Цвет» вместо мелкой ссылки (клиент 19.09, согласовано голосовым) ──
// Покупательница не нашла, где править шрифт: ссылка «Шрифт и цвет» была серой и мелкой.
// ⛔ Механику менять нельзя: список выезжает ВНИЗ в самой карточке и сдвигает блоки под собой.
// Всплывающее окно поверх макета на телефоне закроет форму — клиент переспрашивал об этом дважды.
test('вход в настройки — две кнопки, список раскрывается в карточке', () => {
  assert.match(код, /data-fc="font"/, 'кнопка «Шрифт» пропала');
  assert.match(код, /data-fc="color"/, 'кнопка «Цвет» пропала');
  assert.doesNotMatch(код, /<details class="opt-font"/,
    'вернулась мелкая ссылка-details вместо двух кнопок');
  assert.match(код, /data-role="fc-font"/, 'на кнопке обязано стоять текущее имя шрифта');
  assert.match(код, /data-role="fc-color"/, 'на кнопке обязан стоять кружок текущего цвета');
  // Открыта всегда ровно одна панель, иначе карточка вырастет выше согласованных 211 px.
  const m = код.match(/_переключитьПалитру\(optId, какая, body\) \{([\s\S]*?)\n  \}/);
  assert.ok(m, 'переключатель панелей должен существовать');
  assert.match(m[1], /список\.hidden = стало !== 'font'/, 'список шрифтов обязан гаснуть');
  assert.match(m[1], /цвета\.hidden = стало !== 'color'/, 'палитра цвета обязана гаснуть');
});

// ⚠️ `display: flex` у списков перебивает атрибут hidden: без явного правила панели остаются
