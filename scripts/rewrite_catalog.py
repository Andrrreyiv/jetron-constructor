НОВЫЕ_ЦВЕТА = {"lightblue": {"id": "lightblue", "name": "Голубой", "hex": "#4fb3f7"}}

# Слаги для линеек с кириллическим именем. Догадка: реальных URL клиент не дал.
СЛАГИ = {"Волна": "volna", "Фаворит": "favorit"}


def _цвет(слово):
    """Слово расцветки из имени файла -> id цвета палитры."""
    for основа, id_ in ОСНОВЫ_ЦВЕТОВ.items():
        if слово.startswith(основа):
            return id_
    raise KeyError(f"незнакомая расцветка: {слово!r}")


# Высота кадра, на которой калиброван `zoneTemplate`: до 30.08 все 45 мокапов
# добивались белым до 1200, и доли зон меряли от неё.
ЭТАЛОННАЯ_ВЫСОТА = 1200


def наборы_зон(шаблон, кадры, эталон=ЭТАЛОННАЯ_ВЫСОТА, сдвиг=0):
    """Общий шаблон зон -> свой набор на каждую линейку.

    Кадр перестал быть общим: у Champion он 992 px, у Star 1110. Зона задана
    долей ОТ ХОЛСТА, поэтому один и тот же шаблон на разных линейках сажает
    номер в разные места формы — на Champion промах доходит до 68 px.

    До 01.09 пересчёт был чистым делением: `y_new = y_old * 1200 / H`. Он верен,
    только пока форма стоит на прежнем месте по вертикали, а меняется лишь нижняя
    кромка кадра — так было 30.08, когда ушла белая добивка снизу и пиксели формы
    не сдвинулись ни на один у всех 45 файлов (сверено с git).

    `сдвиг` — на сколько пикселей форма ПОДНЯЛАСЬ, когда срезали верхнюю полосу
    (`TOP_PX` в `normalize_mockups.py`). Тогда абсолютная строка зоны становится
    `y_old * эталон - сдвиг`, и делить на новый кадр надо уже её. Высота `h`
    делится БЕЗ вычитания: подъём двигает зону целиком, но не сжимает её.

    Ширина кадра как была 900, так и осталась, поэтому `x` и `w` не трогаем.
    """
    return {
        линейка: [
            {
                **зона,
                "box": {
                    **зона["box"],
                    "y": round((зона["box"]["y"] * эталон - сдвиг) / высота, 4),
                    "h": round(зона["box"]["h"] * эталон / высота, 4),
                },
            }
            for зона in шаблон
        ]
        for линейка, (_, высота) in кадры.items()
    }


def _вид(box, рамки):
    """Вид, к которому относится зона: перёд и зад занимают разные полосы `x`."""
    центр = box["x"] + box["w"] / 2

    def промах(вид):
        из_ = рамки[вид][0]
        return max(из_.x - центр, центр - (из_.x + из_.w), 0)

    return min(рамки, key=промах)


def _перенести(box, из_, в):
    """Доля от холста клиента -> доля от нашего холста через рамку комплекта.

    По каждой оси независимо: положение зоны внутри комплекта сохраняется,
    размер едет за размером комплекта по этой же оси.
    """
    return {
        **box,
        "x": round(в.x + (box["x"] - из_.x) * в.w / из_.w, 4),
        "y": round(в.y + (box["y"] - из_.y) * в.h / из_.h, 4),
        "w": round(box["w"] * в.w / из_.w, 4),
        "h": round(box["h"] * в.h / из_.h, 4),
    }


def пересчитать_переопределения(переопределения, рамки):
    """Расстановка зон, сделанная клиентом руками, -> на наш мокап.

    `рамки` — form_id -> вид -> (рамка комплекта на картинке клиента, рамка у нас),
    каждая долями СВОЕГО холста. Формы, которых там нет, возвращаются НЕТРОНУТЫМИ:
    их картинка не наша, замерить рамку не по чему, а перенос наугад выбрасывает
    зоны за холст (замер по `champion-sinij3`: три зоны на шортах уезжают на
    1.113..1.147). Пусть лучше останется как есть и будет виден вопрос, чем тихая
    порча чужой работы.

    ⚠️ Прежняя версия множила `y` и `h` на 1200/H, а `x` и `w` не трогала вовсе.
    Это чинило ровно одно — снятую снизу белую добивку — и молча считало, что
    комплект на картинке клиента стоит там же и того же размера, что у нас. Он не
    стоит: у заднего вида боевая рамка 303x521 в кадре 900x1200 против нашей
    419x717 в кадре 900x992. Фамилия от этого уезжала клиенту на воротник.

    Перенос анизотропный, потому что боевая картинка — композит, собранный не из
    одного масштаба: пропорция переднего вида там 0.518 против 0.582 у остальных
    трёх, то есть вид растянут по вертикали. Общий множитель на обе оси вернул бы
    тот же промах, только меньше.
    """
    out = {}
    for form_id, зоны in переопределения.items():
        формы = рамки.get(form_id)
        if not формы:
            out[form_id] = зоны
            continue
        out[form_id] = {
            ключ: _перенести(box, *формы[_вид(box, формы)]) for ключ, box in зоны.items()
        }
    return out


def расставить_наборы(config, кадры, сдвиг=СДВИГ_ФОРМЫ):
    """Кладёт пересчитанные наборы в конфиг и переводит на них формы.

    Одного пересчёта мало: движок берёт зоны как `form.zones ||
    config.zoneSets[form.zoneSet] || config.zoneTemplate` (`app.browser.js:65-68`).
    Без `zoneSet` у формы он молча падает на общий `zoneTemplate` — на доли,
    калиброванные под холст 1200, — и весь пересчёт проходит мимо, а промах
    (до 68 px по Champion) виден только глазами.

    `zoneTemplate` остаётся в конфиге нетронутым: он и есть эталон 1200,
    от которого считаются все наборы, и запасной вариант для формы без линейки.

    `сдвиг` по умолчанию берётся из нормализатора (`СДВИГ_ФОРМЫ`), а не пишется
    здесь числом: это единственная боевая точка входа, и забытый в ней подъём
    молча увёл бы все зоны на срезанную полосу. Явный `сдвиг=0` остаётся —
    им проверяется старое поведение, когда кадр менялся только снизу.
    """
    config["zoneSets"] = наборы_зон(config["zoneTemplate"], кадры, сдвиг=сдвиг)
    for форма in config["forms"]:
        форма["zoneSet"] = форма["line"]
    return config


def _слаг(линейка, slugs):
    return slugs.get(линейка) or СЛАГИ.get(линейка) or линейка.lower()


def rewrite(config, mapping, готовые=None):
    """Приводит состав каталога к карте мокапов. Возвращает тот же объект.

    `готовые` — имена мокапов, уже прогнанных нормализацией. Форма, чьего мокапа
    там нет, остаётся на прежней картинке: перевести её на имя будущего файла
    заранее — значит выложить каталог с битыми превью. None = готовы все.
    """
    slugs = config["catalog"]["lineSlugs"]
    прежние = {f["id"]: f["images"] for f in config["forms"]}
    палитра = {c["id"]: c for c in config["colors"]}

    цели = [
        (линейка, цель)
        for линейка, d in mapping["lines"].items()
        for цель in d["files"].values()
    ]

    for _, цель in цели:
        id_ = _цвет(цель.split(" ", 1)[1])
        if id_ not in палитра:
            палитра[id_] = НОВЫЕ_ЦВЕТА[id_]
            config["colors"].append(НОВЫЕ_ЦВЕТА[id_])

    порядок = {c["id"]: i for i, c in enumerate(config["colors"])}
    линейки = {л: i for i, л in enumerate(mapping["lines"])}
    # Своя раскладка зон у 12 форм. Пересборка не имеет права её обнулить:
    # зоны расставляет клиент руками (голосовое 28.08).
    прежние_наборы = {f["id"]: f["zoneSet"] for f in config["forms"] if "zoneSet" in f}

    формы = []
    for линейка, цель in цели:
        id_ = _цвет(цель.split(" ", 1)[1])
        ключ = f"{_слаг(линейка, slugs)}-{id_}"
        # Расширение берём от нормализации, а не литералом: имя цели в карте дано
        # без расширения, и разъезд конфига с диском дал бы пустые превью у всех 45.
        путь = f"assets/mockups/{цель}.{FORMAT.lower()}"
        картинки = (
            {"front": путь, "back": путь, "shoulder": None}
            if готовые is None or цель in готовые
            else прежние[ключ]
        )
        формы.append(
            {
                "id": ключ,
                "line": линейка,
                "colorId": id_,
                "color": палитра[id_]["name"],
                "colorHex": палитра[id_]["hex"],
                "images": картинки,
            }
        )
        if ключ in прежние_наборы:
            формы[-1]["zoneSet"] = прежние_наборы[ключ]

    # Порядок расцветок в панели задаётся порядком списка forms, а не палитрой:
    # сортируем по цвету, внутри цвета — по порядку линеек в карте.
    формы.sort(key=lambda f: (порядок[f["colorId"]], линейки[f["line"]]))
    config["forms"] = формы

    # Панель рисует ВСЮ палитру без фильтра, поэтому цвет, оставшийся без форм
    # (коралловый после снятия его у Legend), был бы кликабельным образцом с «0 вариантов».
    живые = {f["colorId"] for f in формы}
    config["colors"] = [c for c in config["colors"] if c["id"] in живые]

    for линейка in list(slugs):
        if линейка not in линейки:
            slugs.pop(линейка)
    for линейка in линейки:
        slugs.setdefault(линейка, _слаг(линейка, slugs))

    return config
