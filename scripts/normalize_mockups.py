# -*- coding: utf-8 -*-
"""Нормализация мокапов формы к единому кадру конструктора.

Зачем: у клиента ощущение «одна линейка большая и хорошая, остальные мелкие».
Причина не в качестве файлов, а в пропорции — холст конструктора 0.75, а мокапы
приходят 19 разных размеров и 15 разных пропорций и ложатся с полями.

Контракт: форма в каждом кадре встаёт в ОДНУ И ТУ ЖЕ геометрическую рамку.
Зоны нанесения заданы долями 0..1 от холста, поэтому одинаковая рамка означает,
что зоны переносимы и расставлять их надо один раз на линейку, а не 45 раз.
"""
from pathlib import Path

import numpy as np
from PIL import Image

# Ширина кадра. Она и только она фиксирована: форма всегда упирается в ШИРИНУ
# (пара «перёд + зад» шире, чем выше — 1.05..1.34), поэтому ширина задаёт масштаб.
CANVAS_WIDTH = 900

# ⚠️ ГЛАВНОЕ, что нужно знать про этот файл. Высота холста в конструкторе НЕ жёсткая:
# `CanvasView.setBackground` (src/js/ui/canvas.browser.js:49-59) считает
# `scale = ширина холста / ширина картинки` и следом делает
# `canvas.setDimensions({ height: картинка.height * scale })` — то есть окно
# подстраивается под пропорцию картинки, какой бы она ни была.
# Проверено 2026-08-29 живым браузером на стенде: подсунули фон 1100x1200, высота холста
# поехала 800 -> 654.5 при ширине 600, ровно 600 * 1200 / 1100. Второе подтверждение —
# скриншоты клиента с его собственным файлом 1100x1200: пустой полосы под шортами нет.
#
# Отсюда вывод, который отменяет всю прежнюю логику этого файла: пустая полоса снизу
# бралась НЕ из несовпадения пропорций с окном, а из того, что мы сами добивали каждый
# кадр белым до высоты 1200. Окно тут ни при чём, «геометрия картинки» тоже —
# лишнее белое поле рисовали мы.
#
# Поэтому высота кадра больше не константа, а считается по линейке (`line_canvas`):
# самая высокая форма линейки + верхняя полоса + нижний зазор. Внутри линейки кадр
# один на все расцветки — это и есть контракт переносимости зон, потому что зоны
# заданы долями 0..1 от холста, а расставляет их клиент один раз на линейку.
# Между линейками кадры законно разные: у Champion формы низкие (674..736 px),
# у Star высокие (776..854), и общий кадр на всех вернул бы Champion ту самую полосу.

# Верхняя рабочая полоса, пиксели. Клиент 2026-08-29 (голосовое): «форма слишком высоко
# задрана, она задевает плашку и кнопку» и «надо пространство сверху оставить для рабочих
# зон, мы туда будем что-то добавлять». Плашка линейки и кнопка «перейти в карточку»
# стоят в `.line-badge` абсолютом от `top: 0` (stand.css) и занимают ~65 px в координатах
# холста шириной 900. 216 px оставляет их целиком плюс запас под кнопки, которые он
# собирается добавить сам.
TOP_PX = 216

# Нижний зазор, пиксели. Клиент 2026-08-29: «снизу можно убрать отступ, можно такой
# вариант». Полностью в ноль не жмём: шорты не должны касаться края карточки.
BOTTOM_PX = 40

# Фон кадра. Исходники поставщика на белом, белый и оставляем — так нормализация
# ничего не придумывает от себя.
BACKGROUND = (255, 255, 255)

WHITE_CUT = 240
MIN_INK_PIXELS = 3

# Формат готового мокапа. Замер 28.08 на пяти худших кадрах: PNG 514-837 КБ,
# WebP q92 — 75-137 КБ при RMSE 1.1-2.3 из 255, то есть глазом не отличить.
# JPEG q92 проигрывает и по весу (107-162 КБ), и по ошибке (1.4-2.6).
# 45 мокапов в PNG это ~30 МБ на мобильном интернете, в WebP — около 5 МБ.
FORMAT = "WEBP"
QUALITY = 92


def plan(mapping, source_dir=None):
    """Карта соответствия -> плоский список задач нормализации.

    Ключи с подчёркиванием (`_`, `_source_dir`, `_batch`, `_rename`,
    `_names_provisional`) — пояснения для человека, а не файлы, поэтому обход
    идёт строго по `lines[*].files`, а не по всем ключам подряд.
    """
    root = Path(source_dir or mapping.get("_source_dir", "."))
    return [
        {"line": line, "src": root / name, "target": target}
        for line, block in mapping["lines"].items()
        for name, target in block["files"].items()
    ]


def ink_bbox(arr, white_cut=WHITE_CUT, min_pixels=MIN_INK_PIXELS):
    """Рамка краски в кадре: (x0, y0, x1, y1) включительно.

    Строка и столбец считаются содержательными, только если краски в них
    набралось не меньше `min_pixels` — иначе одиночная тёмная точка сжатого
    JPEG растянет рамку на весь кадр и запорет масштаб.
    """
    ink = arr.min(axis=2) < white_cut
    rows = np.nonzero(ink.sum(axis=1) >= min_pixels)[0]
    cols = np.nonzero(ink.sum(axis=0) >= min_pixels)[0]
    if not len(rows) or not len(cols):
        raise ValueError("в кадре нет краски: сплошной фон")
    return int(cols[0]), int(rows[0]), int(cols[-1]), int(rows[-1])


def fitted_height(bbox, width=CANVAS_WIDTH):
    """Высота формы после вписывания по ширине кадра.

    Ширину форма занимает всегда целиком: пара «перёд + зад» шире, чем выше
    (1.05..1.34), поэтому масштаб задаёт именно ширина, а высота из него следует.
    """
    src_w = bbox[2] - bbox[0] + 1
    src_h = bbox[3] - bbox[1] + 1
    return round(src_h * width / src_w)


def line_canvas(bboxes, width=CANVAS_WIDTH, top_px=TOP_PX, bottom_px=BOTTOM_PX):
    """Кадр ОДНОЙ линейки по рамкам краски всех её расцветок.

    Высоту задаёт самая высокая форма линейки: она получает нижний зазор ровно
    `bottom_px`, остальные — чуть больше. Общий кадр на все 45 брать нельзя:
    формы Champion на 180 px ниже формы Star, и Champion снова получил бы
    ту самую белую полосу, из-за которой всё и началось.
    """
    if not bboxes:
        raise ValueError("линейка без файлов: кадр не из чего считать")
    return (width, max(fitted_height(b, width) for b in bboxes) + top_px + bottom_px)


def frame(bbox, canvas, top_px=TOP_PX, bottom_px=BOTTOM_PX):
    """Куда и с каким масштабом положить рамку краски на холст.

    Верх у всех расцветок линейки один и тот же — ровно `top_px`. Высота у них
    законно разная: это настоящая пропорция формы, и подгонять её под общее
    число значило бы искажать шорты у одних ради других.

    Второе слагаемое в `min` — страховка, а не рабочий путь. Ширина упирается
    первой на всех 45 кадрах; клапан по высоте сработает, только если попадётся
    небывало вытянутый исходник, и лучше он не влезет в кадр, чем вылезет за него.
    """
    cw, ch = canvas
    src_w = bbox[2] - bbox[0] + 1
    src_h = bbox[3] - bbox[1] + 1
    scale = min(cw / src_w, (ch - top_px - bottom_px) / src_h)
    width = round(src_w * scale)
    return {
        "scale": scale,
        "left": round((cw - width) / 2),
        "top": top_px,
        "width": width,
        "height": round(src_h * scale),
    }


def normalize(im, canvas, **kw):
    """Кадр поставщика -> кадр конструктора.

    Возвращает картинку ровно размера холста, где форма стоит в общей рамке.
    Увеличение — Lanczos: нейросетевого апскейлера на машине нет, и ставить его
    в срок заказа я не буду. На 11 файлах из 45 увеличение почти двукратное,
    мягкость на швах и цифрах там будет видна — это вопрос 1 клиенту.
    """
    im = im.convert("RGB")
    box = ink_bbox(np.asarray(im, "uint8"))
    f = frame(box, canvas=canvas, **kw)

    forma = im.crop((box[0], box[1], box[2] + 1, box[3] + 1))
    forma = forma.resize((f["width"], f["height"]), Image.LANCZOS)

    out = Image.new("RGB", canvas, BACKGROUND)
    out.paste(forma, (f["left"], f["top"]))
    return out


def save_mockup(im, path, fmt=FORMAT, quality=QUALITY):
    """Записать готовый кадр и вернуть фактический путь.

    Имя цели в `mockup-map.json` дано БЕЗ расширения намеренно: подставляет его
    только эта функция, поэтому формат задан в одном месте и не может разойтись
    с путями, которые прописывает в конфиг `rewrite_catalog.py`.
    """
    dst = Path(path).with_suffix("." + fmt.lower())
    im.save(dst, fmt, quality=quality, method=6)
    return dst
